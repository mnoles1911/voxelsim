def _fbm(rng: np.random.Generator, n: int, octaves: int = 6) -> np.ndarray:
    """Fractal value noise in [-1, 1]. Not Perlin, and it does not need to be --
    this only breaks up shapes that are otherwise too geometric."""
    out = np.zeros((n, n))
    amp, total = 1.0, 0.0
    for o in range(octaves):
        size = max(2, int(4 * 2 ** o))
        grid = rng.random((size, size)) * 2 - 1
        yi = np.linspace(0, size - 1, n)
        xi = np.linspace(0, size - 1, n)
        y0 = np.clip(yi.astype(int), 0, size - 2)
        x0 = np.clip(xi.astype(int), 0, size - 2)
        fy = (yi - y0)[:, None]
        fx = (xi - x0)[None, :]
        fy = fy * fy * (3 - 2 * fy)          # smoothstep
        fx = fx * fx * (3 - 2 * fx)
        g = grid[np.ix_(y0, x0)]
        gx = grid[np.ix_(y0, x0 + 1)]
        gy = grid[np.ix_(y0 + 1, x0)]
        gxy = grid[np.ix_(y0 + 1, x0 + 1)]
        out += amp * ((g * (1 - fx) + gx * fx) * (1 - fy) + (gy * (1 - fx) + gxy * fx) * fy)
        total += amp
        amp *= 0.5
    return out / total


def _distance_to(mask: np.ndarray, cell_km: float) -> np.ndarray:
    """Distance in km from every cell to the nearest True cell, by dilation.

    Same construction as world_map.py's inland_reach_km, which is already
    trusted. A two-pass chamfer was tried first and leaked its INF sentinel into
    cells the sweep never reached, which silently zeroed every rainfall term
    downstream (exp(-1e9/260) == 0) and made the whole continent desert. The
    dilation cannot do that: a cell either gets a real step count or the loop
    has provably converged.

    Grids here are a few hundred cells square, so the naive version is fast
    enough and cannot be wrong in that way.
    """
    if not mask.any():
        # No ocean at all: everything is maximally inland. Saturate rather than
        # divide by nothing.
        return np.full(mask.shape, max(mask.shape) * cell_km, dtype=np.float64)
    dist = np.zeros(mask.shape, dtype=np.float64)
    frontier = mask.copy()
    for step in range(1, mask.shape[0] + mask.shape[1] + 2):
        grown = frontier.copy()
        grown[1:, :] |= frontier[:-1, :]
        grown[:-1, :] |= frontier[1:, :]
        grown[:, 1:] |= frontier[:, :-1]
        grown[:, :-1] |= frontier[:, 1:]
        newly = grown & ~frontier
        if not newly.any():
            break
        dist[newly] = step
        frontier = grown
    return dist * cell_km


def _polyline_distance(n: int, pts) -> np.ndarray:
    """Distance in cells from every point to a polyline through `pts`."""
    yy, xx = np.mgrid[0:n, 0:n]
    best = np.full((n, n), float(n * 2))
    for (ay, ax), (by, bx) in zip(pts[:-1], pts[1:]):
        vy, vx = by - ay, bx - ax
        L2 = vy * vy + vx * vx
        if L2 == 0:
            d = np.hypot(yy - ay, xx - ax)
        else:
            t = np.clip(((yy - ay) * vy + (xx - ax) * vx) / L2, 0, 1)
            d = np.hypot(yy - (ay + t * vy), xx - (ax + t * vx))
        best = np.minimum(best, d)
    return best


def _wandering_ridge(rng, n: int, a, b, wander: float):
    """A perturbed polyline from a to b.

    A straight segment with a gaussian falloff reads as a capsule, not a
    mountain range -- it was the most obviously fake thing in the first version
    of this tool. Displacing the interior control points perpendicular to the
    line, midpoint-displacement style, gets a ridge that bends and forks the way
    a real orogen does, for about ten lines.
    """
    steps = 12
    ay, ax = a
    by, bx = b
    vy, vx = by - ay, bx - ax
    L = max(1e-6, math.hypot(vy, vx))
    py, px = -vx / L, vy / L                    # unit perpendicular
    pts = []
    for i in range(steps + 1):
        t = i / steps
        # Zero displacement at the ends so the ridge still joins its anchors.
        env = math.sin(math.pi * t)
        off = (rng.random() * 2 - 1) * wander * L * 0.25 * env
        pts.append((ay + vy * t + py * off, ax + vx * t + px * off))
    return pts


