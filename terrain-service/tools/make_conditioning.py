def write_tiffs(out: Path, spec: WorldSpec, chans: dict) -> None:
    try:
        import rasterio
        from rasterio.transform import from_bounds
    except ImportError:
        sys.exit("rasterio is required to write GeoTIFFs "
                 "(present in terrain-diffusion's venv)")

    out.mkdir(parents=True, exist_ok=True)
    n = spec.cells
    # A plate carree box sized so one cell is CELL_KM across at the equator.
    # tiff_export only needs a consistent CRS/transform across the five files;
    # it works in cells, not in ground units.
    deg = n * CELL_KM / 111.32
    transform = from_bounds(-deg / 2, -deg / 2, deg / 2, deg / 2, n, n)

    for name, arr in chans.items():
        path = out / name
        with rasterio.open(path, "w", driver="GTiff", height=n, width=n, count=1,
                           dtype="float32", crs="EPSG:4326", transform=transform,
                           compress="lzw") as dst:
            dst.write(arr.astype(np.float32), 1)
        print(f"  wrote {path.name:24s} {float(arr.min()):9.1f} .. {float(arr.max()):9.1f}")


def preview(path: Path, spec: WorldSpec, elev, temp, precip, dist_km) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(1, 4, figsize=(20, 5.4), dpi=110)
    land = elev > 0
    # Ocean drawn first in its own ramp, land over it -- sharing one ramp made
    # the shoreline invisible in the first version.
    ax[0].imshow(np.where(land, np.nan, elev), cmap="Blues_r", vmin=-6000, vmax=0)
    a = ax[0].imshow(np.where(land, elev, np.nan), cmap="terrain", vmin=0,
                     vmax=max(1.0, float(np.nanmax(np.where(land, elev, np.nan)))))
    ax[0].contour(np.where(land, 1.0, 0.0), levels=[0.5], colors="k", linewidths=0.8)
    ax[0].set_title(f"elevation  ({elev.min():.0f} .. {elev.max():.0f} m)")
    plt.colorbar(a, ax=ax[0], fraction=0.046)
    for i, (arr, name, cmap) in enumerate([
            (np.where(land, dist_km, np.nan), "km from ocean (continentality)", "magma"),
            (np.where(land, precip, np.nan), "precipitation mm/yr", "YlGnBu"),
            (np.where(land, temp, np.nan), "temperature C", "RdYlBu_r")], start=1):
        im = ax[i].imshow(arr, cmap=cmap)
        ax[i].set_title(name)
        plt.colorbar(im, ax=ax[i], fraction=0.046)
    for a_ in ax:
        a_.set_xticks([])
        a_.set_yticks([])
    fig.suptitle(spec.describe(), fontsize=10)
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    print(f"  wrote {path}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, help="directory for the 5 GeoTIFFs")
    ap.add_argument("--spec", help="JSON file of WorldSpec fields (overrides flags)")
    ap.add_argument("--seed", type=int)
    ap.add_argument("--cells", type=int)
    ap.add_argument("--continents", type=int)
    ap.add_argument("--land-fraction", type=float)
    ap.add_argument("--continentality-km", type=float,
                    help="e-folding distance for the rain decay; THE desert knob")
    ap.add_argument("--coastal-precip-mm", type=float)
    ap.add_argument("--base-temp-c", type=float)
    ap.add_argument("--wind-from-deg", type=float)
    ap.add_argument("--arid-interior", action="store_true",
                    help="shorthand: one big continent, sharp rain decay")
    ap.add_argument("--preview", help="also write a 4-panel PNG here")
    ap.add_argument("--dump-spec", help="write the resolved spec as JSON")
    args = ap.parse_args()

    spec = WorldSpec()
    if args.spec:
        spec = WorldSpec(**{**asdict(spec), **json.loads(Path(args.spec).read_text())})
    if args.arid_interior:
        spec.continents = 1
        spec.land_fraction = 0.5
        spec.continentality_km = 260.0
        spec.cells = max(spec.cells, 200)
    for f in ("seed", "cells", "continents", "land_fraction", "continentality_km",
              "coastal_precip_mm", "base_temp_c", "wind_from_deg"):
        v = getattr(args, f, None)
        if v is not None:
            setattr(spec, f, v)

    print(spec.describe())
    elev = build_elevation(spec)
    temp, seasonality, precip, precip_cv, dist_km = build_climate(spec, elev)

    land = elev > 0
    print(f"  land {land.mean():.1%}, inland reach {dist_km.max():.0f} km, "
          f"land rain {np.percentile(precip[land], 5):.0f}..{np.percentile(precip[land], 95):.0f} mm/yr")
    arid = (precip[land] < 400).mean() if land.any() else 0.0
    print(f"  land below 400 mm/yr (arid): {arid:.1%}")

    write_tiffs(Path(args.out), spec, {
        "heightmap.tif": elev,
        "temperature.tif": temp,
        "temperature_std.tif": seasonality,
        "precipitation.tif": precip,
        "precipitation_cv.tif": precip_cv,
    })
    if args.dump_spec:
        Path(args.dump_spec).write_text(json.dumps(asdict(spec), indent=2))
        print(f"  wrote {args.dump_spec}")
    if args.preview:
        preview(Path(args.preview), spec, elev, temp, precip, dist_km)


if __name__ == "__main__":
    main()
