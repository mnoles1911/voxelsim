def build_elevation(spec: WorldSpec) -> np.ndarray:
    rng = np.random.default_rng(spec.seed)
    n = spec.cells

    # Continent seeds, kept away from the border so coastlines are not clipped.
    margin = n // 6
    seeds = [(int(rng.integers(margin, n - margin)), int(rng.integers(margin, n - margin)))
             for _ in range(max(1, spec.continents))]

    # Broad landmass field: a smooth bump per seed, plus noise for ragged edges.
    field = np.zeros((n, n))
    radius = n / (1.7 * math.sqrt(max(1, spec.continents)))
    yy, xx = np.mgrid[0:n, 0:n]
    for (sy, sx) in seeds:
        r = np.hypot(yy - sy, xx - sx) / radius
        field += np.exp(-r * r)
    field += spec.roughness * 0.8 * _fbm(rng, n)

    # MOUNTAIN RANGES along the lines joining seeds. Long linear features are
    # what a noise field cannot produce and what makes terrain read as tectonic
    # rather than as blobs; they are also what casts the rain shadow below.
    ranges = np.zeros((n, n))
    if spec.range_height_m > 0 and len(seeds) >= 1:
        if len(seeds) > 1:
            pairs = [(seeds[i], seeds[(i + 1) % len(seeds)]) for i in range(len(seeds))]
        else:
            # One continent still gets a range: run it across the landmass on a
            # random bearing rather than a fixed diagonal.
            ang = rng.random() * math.pi
            r = n * 0.34
            cy, cx = seeds[0]
            pairs = [((cy - r * math.cos(ang), cx - r * math.sin(ang)),
                      (cy + r * math.cos(ang), cx + r * math.sin(ang)))]
        w_cells = max(1.0, spec.range_width_km / CELL_KM)
        # Width varies along strike as well as height. With a constant width the
        # result is a uniform ribbon -- recognisably a drawn curve rather than an
        # orogen, even after the ridge line itself is made to wander.
        wmod = 0.55 + 0.9 * np.clip(_fbm(rng, n, octaves=3) * 0.5 + 0.5, 0, 1)
        for a, b in pairs:
            d = _polyline_distance(n, _wandering_ridge(rng, n, a, b, spec.range_wander))
            ranges = np.maximum(ranges, np.exp(-(d / (w_cells * wmod)) ** 2))
        # Along-strike height variation, so the crest rises and falls into
        # distinct massifs instead of holding one height for its whole length.
        ranges *= 0.45 + 0.85 * np.clip(_fbm(rng, n, octaves=4) * 0.5 + 0.5, 0, 1)

    # Sea level chosen to hit the requested land fraction exactly, which is far
    # more predictable for a designer than tuning an offset by hand.
    thresh = np.quantile(field, 1.0 - spec.land_fraction)
    land = field > thresh
    span = max(1e-6, field.max() - thresh)
    above = np.clip((field - thresh) / span, 0, 1)

    # Interior relief. Without this the continent is a featureless ramp from
    # coast to 900 m, which reads as a mudflat once the diffusion refines it.
    # Two extra octave bands, both damped near the coast so the shoreline stays
    # where land_fraction put it.
    hills = (0.6 * _fbm(rng, n, octaves=5) + 0.4 * _fbm(rng, n, octaves=7))
    relief = np.clip(hills * 0.5 + 0.5, 0, 1) * 700.0 * np.clip(above * 2.2, 0, 1)

    elev = np.where(
        land,
        above * 700.0 + relief + ranges * spec.range_height_m,
        -np.clip((thresh - field) / max(1e-6, thresh - field.min()), 0, 1) * spec.abyss_depth_m,
    )
    return elev.astype(np.float32)


def build_climate(spec: WorldSpec, elev: np.ndarray):
    n = spec.cells
    land = elev > 0

    # Continentality: km to the nearest ocean cell. The whole point.
    dist_km = _distance_to(~land, CELL_KM)
    dist_km[~land] = 0.0

    # Latitude, mapped onto the grid's rows. Row 0 is the poleward edge.
    lat_t = np.linspace(1.0, 0.0, n)[:, None] * np.ones((1, n))   # 1 = pole
    latitude_deg = 55.0 - 60.0 * lat_t                            # ~-5..55 N

    # --- temperature -------------------------------------------------------
    temp = spec.base_temp_c + (0.5 - lat_t) * spec.lat_temp_drop_c
    temp = temp - 6.5 * np.maximum(0.0, elev) / 1000.0            # lapse rate
    # Continental interiors swing further from the maritime mean, which is what
    # bio_4 measures; the mean itself barely moves, so only seasonality uses it.
    contin = 1.0 - np.exp(-dist_km / max(1e-6, spec.continentality_km))

    # --- precipitation -----------------------------------------------------
    # Latitude belt: wet near the equator and in the mid-latitude storm track,
    # dry in the subtropics around 25 degrees -- Earth's actual desert band.
    band = (0.55 + 0.45 * np.cos(np.radians(latitude_deg) * 2.2)
            - 0.55 * np.exp(-((np.abs(latitude_deg) - 25.0) / 9.0) ** 2))
    band = np.clip(band, 0.12, 1.35)

    precip = spec.coastal_precip_mm * band
    precip = precip * np.exp(-dist_km / max(1e-6, spec.continentality_km))

    if spec.orographic_strength > 0:
        precip = precip * _orographic(spec, elev)

    precip = np.maximum(precip, spec.min_precip_mm)
    precip = np.where(land, precip, spec.coastal_precip_mm * band)  # ocean stays wet

    # bio_4: sd(monthly) x100. Maritime ~400, strongly continental ~2000.
    seasonality = 350.0 + 1500.0 * contin + 6.0 * np.maximum(0.0, -temp)
    # bio_15: rainfall is peakier where it is scarcer.
    precip_cv = np.clip(35.0 + 90.0 * (1.0 - precip / max(1.0, spec.coastal_precip_mm)), 20.0, 150.0)

    return (temp.astype(np.float32), seasonality.astype(np.float32),
            precip.astype(np.float32), precip_cv.astype(np.float32), dist_km)


def _orographic(spec: WorldSpec, elev: np.ndarray) -> np.ndarray:
    """Rain-shadow multiplier: wet where the wind climbs, dry in the lee.

    March a parcel downwind, tracking the highest ground it has crossed. Rising
    against that maximum wrings moisture out (windward gets a boost); once past
    the crest the parcel is spent, and stays spent until it reaches sea again.
    Crude, one-pass, and enough to put a desert behind a mountain range -- which
    is the entire ask.
    """
    n = elev.shape[0]
    th = math.radians(spec.wind_from_deg)
    dy, dx = -math.cos(th), -math.sin(th)     # direction the wind blows TOWARD
    steps = int(n * 1.2)
    crest = np.zeros_like(elev)
    yy, xx = np.mgrid[0:n, 0:n].astype(np.float64)
    for s in range(1, steps):
        sy = np.clip((yy - dy * s).astype(int), 0, n - 1)
        sx = np.clip((xx - dx * s).astype(int), 0, n - 1)
        upwind = elev[sy, sx]
        # Ocean upwind resets the parcel: it has picked up moisture again.
        crest = np.where(upwind <= 0, 0.0, np.maximum(crest, upwind))
    lee = np.clip((crest - np.maximum(elev, 0)) / 1500.0, 0, 1)
    windward = np.clip((np.maximum(elev, 0) - crest) / 1200.0, 0, 1)
    k = spec.orographic_strength
    return np.clip(1.0 + 0.5 * k * windward - 0.75 * k * lee, 0.12, 1.8)


