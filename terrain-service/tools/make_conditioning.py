#!/usr/bin/env python3
"""Author the coarse conditioning rasters terrain-diffusion generates from.

WHY THIS EXISTS. The model is always conditioned on a 5-channel coarse sketch
(elevation, temperature, temp seasonality, precipitation, precip CV). By default
that sketch comes from `synthetic_map.py`: Perlin FBm quantile-matched to
Earth's histogram. Two consequences, both measured (docs/worldgen-levers.md):

  * Perlin FBm is isotropic, so every world is an archipelago. Inland reach
    never exceeded 92 km across four seeds. A seed picks a realization, not a
    process.
  * Precipitation is an INDEPENDENT Perlin field, never touched by elevation or
    by distance from ocean. There is no orographic rainfall, no rain shadow and
    no continentality, so DESERTS CANNOT FORM AT ANY LANDMASS SCALE -- a
    315,000 km2 continent generated by tuning frequency_mult alone still
    classified DESERT 0.0%.

This tool writes the sketch instead, with the causal structure the default
generator omits. It does not touch the model: `tiff-export` feeds these rasters
through the same pipeline, and `--snr` decides how literally they are obeyed.

WHAT IT MODELS, and why each one is here rather than left to the diffusion:

  * CONTINENTS as seeded blobs joined by linear ranges. Perlin cannot make a
    long feature; plate boundaries are long, and that is most of why Earth does
    not look like this model's default output.
  * CONTINENTALITY. Precipitation decays with distance from open water, because
    moisture comes off the ocean and is spent crossing land. THIS is what makes
    a dry interior, and it is the single reason this tool exists.
  * OROGRAPHIC RAIN SHADOW. Terrain rising against the prevailing wind wrings
    out moisture; the lee side is dry. Computed by marching the wind vector
    across the elevation field and accumulating lift.
  * LATITUDE. Temperature falls toward the poles; precipitation peaks near the
    equator and in the mid-latitude storm belt, with subtropical dry zones near
    +/-25 degrees -- which is where Earth's deserts actually are.
  * LAPSE RATE. Temperature falls ~6.5 C/km with elevation, matching biome.h's
    treeline derivation.

NOT A SIMULATION. This is a plausible-looking sketch at 7.68 km per cell, whose
only job is to give the diffusion model a large-scale layout worth refining.
Every constant below is a designer-facing dial, not a physical claim.

KNOWN LIMITATION, stated because the preview makes it obvious: the mountain
ranges still read as drawn ribbons rather than as orogens, even with a wandering
ridge line and along-strike width/height variation. Chasing that further here
would be misplaced effort. The elevation channel's default `cond_snr` is 0.3 --
deliberately loose -- so the model is free to substantially reinterpret this
geometry, and it is far better at mountains than a dozen lines of numpy is. What
this file must get right is the LARGE-SCALE LAYOUT and, above all, the climate
fields, because those are the parts the model cannot infer. Raise `--snr` on
channel 0 only if you want your drawn shapes obeyed literally.

THE NATURAL-LANGUAGE SEAM. Every knob is a named scalar in WorldSpec. Mapping
"a big temperate continent with a dry interior and a wet west coast" onto that
struct is a small, well-posed translation job -- and it is the ONLY part of the
NL-to-world path that needs a language model. Everything downstream is this file
plus terrain-diffusion. Keep the spec small and human-meaningful for that reason.

Usage:
    python tools/make_conditioning.py --out cond/ --continents 2 --arid-interior
    python tools/make_conditioning.py --out cond/ --spec myworld.json
    python tools/make_conditioning.py --out cond/ --preview preview.png

Then hand the directory to terrain-diffusion:
    python -m terrain_diffusion <checkpoint> tiff-export cond/ out.tif \\
        --snr 0.2,0.2,1.0,0.2,1.0
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path

import numpy as np

#: One conditioning cell is one coarse cell: 256 fine pixels x 30 m.
CELL_KM = 256 * 30 / 1000.0


@dataclass
class WorldSpec:
    """Everything that decides the world. The natural-language target."""

    # --- shape -------------------------------------------------------------
    cells: int = 160                    # square grid; 160 -> ~1229 km across
    seed: int = 20260719
    continents: int = 2                 # major landmasses
    land_fraction: float = 0.38         # target, hit by choosing the sea level
    roughness: float = 0.55             # 0 = smooth blobs, 1 = ragged coastlines
    #: Mountain ranges are drawn along the lines JOINING continent seeds -- a
    #: crude stand-in for plate collision, and the one feature Perlin cannot
    #: produce. 0 disables them.
    range_height_m: float = 3200.0
    range_width_km: float = 90.0
    #: How far the ridge line wanders off the straight path between its
    #: anchors. 0 gives a capsule, which is what a straight segment with a
    #: gaussian falloff looks like and is unmistakably artificial.
    range_wander: float = 0.55
    abyss_depth_m: float = 5000.0

    # --- climate -----------------------------------------------------------
    #: Mean temperature at the map's centre latitude, before lapse rate.
    base_temp_c: float = 12.0
    #: How much colder the poleward edge is than the equatorward edge.
    lat_temp_drop_c: float = 26.0
    #: Rain at the coast, before continentality and orography.
    coastal_precip_mm: float = 1400.0
    #: e-folding distance for the continentality decay. THE desert knob:
    #: smaller = drier interiors. 350 km puts a 1200 km continent's centre at
    #: about 18% of its coastal rainfall.
    continentality_km: float = 350.0
    #: Prevailing wind, degrees clockwise from north (270 = westerlies).
    wind_from_deg: float = 270.0
    #: How hard the rain shadow bites, 0 disables orography.
    orographic_strength: float = 1.0
    #: Floor, so nowhere is bone dry unless you ask for it.
    min_precip_mm: float = 40.0

    def describe(self) -> str:
        return (f"{self.cells}x{self.cells} cells ({self.cells * CELL_KM:.0f} km), "
                f"{self.continents} continent(s), land {self.land_fraction:.0%}, "
                f"coastal rain {self.coastal_precip_mm:.0f} mm/yr decaying over "
                f"{self.continentality_km:.0f} km")


