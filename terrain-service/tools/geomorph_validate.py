def _tile_url(lat: int, lon: int) -> str:
    ns = "N%02d" % lat if lat >= 0 else "S%02d" % (-lat)
    ew = "E%03d" % lon if lon >= 0 else "W%03d" % (-lon)
    n = f"Copernicus_DSM_COG_10_{ns}_00_{ew}_00_DEM"
    return f"/vsicurl/https://copernicus-dem-30m.s3.amazonaws.com/{n}/{n}.tif"


def _square_resample(a: np.ndarray, factor: float) -> np.ndarray:
    """Resample the x axis by ``factor`` with bilinear interpolation.

    GLO-30 is on a geographic grid, so its cells are 1 arcsec tall and 1 arcsec wide --
    30.87 m by ``30.87 * cos(lat)`` m. Every metric in this package assumes **square**
    cells (slope is ``hypot`` of two differences that are implicitly at the same pitch;
    the geomorphon rays step ``sqrt(2)`` on the diagonal). Feeding a 46-degree-latitude
    window in raw would report the x-direction slope 45% too small, so the grid is
    resampled to square metric cells before anything else touches it.
    """
    h, w = a.shape
    new_w = int(round(w * factor))
    src = np.linspace(0.0, w - 1.0, new_w)
    i0 = np.floor(src).astype(int)
    i1 = np.minimum(i0 + 1, w - 1)
    t = (src - i0)[None, :]
    return a[:, i0] * (1.0 - t) + a[:, i1] * t


def fetch_window(win: Window, size: int, cache_dir: str, *, verbose: bool = True):
    """Read a GLO-30 window and return ``(z_metres, cell_m)`` on square cells."""
    path = os.path.join(cache_dir, f"{win.case}_{size}.npy")
    if os.path.exists(path):
        return np.load(path), ARCSEC_M
    import rasterio
    from rasterio.windows import Window as RWindow

    os.environ.setdefault("GDAL_DISABLE_READDIR_ON_OPEN", "EMPTY_DIR")
    lat_c = win.lat + 0.5
    cosl = math.cos(math.radians(lat_c))
    src_cols = int(math.ceil(size / cosl)) + 2
    if verbose:
        print(f"  fetching {win.case}: {size}x{src_cols} px at ({win.lat},{win.lon})",
              flush=True)
    with rasterio.open(_tile_url(win.lat, win.lon)) as ds:
        a = ds.read(1, window=RWindow(win.col0, win.row0, src_cols, size)).astype(
            np.float64)
    if not np.isfinite(a).all():
        raise RuntimeError(f"{win.case} window contains voids; move it")
    z = _square_resample(a, cosl)[:, :size]
    if z.shape != (size, size):
        raise RuntimeError(f"{win.case} came back {z.shape}, wanted {(size, size)}")
    os.makedirs(cache_dir, exist_ok=True)
    np.save(path, z)
    return z, ARCSEC_M


def etopo_window(case: str, size: int, cache_dir: str):
    """Fallback: a window of the local ETOPO 10-arcmin grid. Real, and far too coarse."""
    import rasterio

    path = r"D:\terrain-diffusion\data\global\etopo_10m.tif"
    picks = {"alpine": (250, 1090), "fluvial_upland": (300, 630),
             "plains": (295, 620), "desert_dunes": (400, 1180),
             "desert_mountains": (300, 600)}
    r0, c0 = picks.get(case, (250, 1090))
    n = min(size, 128)
    with rasterio.open(path) as ds:
        a = ds.read(1, window=((r0, r0 + n), (c0, c0 + n))).astype(np.float64)
    return a, 10.0 * 60.0 * ARCSEC_M   # 10 arcmin


# --------------------------------------------------------------------------- sweeps
def _quadrants(z):
    h, w = z.shape
    return [z[:h // 2, :w // 2], z[:h // 2, w // 2:],
            z[h // 2:, :w // 2], z[h // 2:, w // 2:]]


def sweep_earth(args) -> dict:
    """Five real classes plus four controls, all at GLO-30's 30 m."""
    fields: dict = {}
    for win in MANIFEST:
        if args.source == "etopo":
            z, cell = etopo_window(win.case, args.size, args.cache)
        else:
            z, cell = fetch_window(win, args.size, args.cache)
        fields[win.case] = (z, cell)

    ref_z, cell = fields["alpine"]
    shape = ref_z.shape
    fields["fbm_h075"] = (
        G.fbm(shape, cell, hurst=0.75, seed=1,
              rms_m=float(ref_z.std())), cell)
    fields["value_noise"] = (
        G.value_noise(shape, cell, seed=2, octaves=9,
                      rms_m=float(ref_z.std())), cell)
    fields["surrogate_alpine"] = (
        G.spectrum_matched_surrogate(ref_z, cell, seed=3), cell)
    fields["surrogate_fluvial"] = (
        G.spectrum_matched_surrogate(fields["fluvial_upland"][0], cell, seed=7), cell)
    fields["shuffled_alpine"] = (G.shuffled(ref_z, cell, seed=4), cell)

    cases, reps, objs = {}, {}, {}
    for name, (z, c) in fields.items():
        print(f"  measuring {name} ...", flush=True)
        cases[name] = R.describe(z, c, search_m=args.search_m)
        ctx = G.flow_context(z, c)
        objs[name] = {
            "slope_area": _safe_sa(ctx),
            "variogram": G.variogram(z, c),
            "hypsometry": G.hypsometry(z, c),
        }
        reps[name] = [R.describe(q, c, search_m=args.search_m, skip_flow=False)
                      for q in _quadrants(z)] if args.replicates else []

    # The control has to be audited too: a surrogate that is rougher than the field it
    # was made from is a strawman, and this is the number that says whether it is.
    fidelity = []
    for real, surr in (("alpine", "surrogate_alpine"),
                       ("fluvial_upland", "surrogate_fluvial")):
        v1 = objs[real]["variogram"]
        v2 = objs[surr]["variogram"]
        r = v2.gamma_m2 / v1.gamma_m2
        fidelity.append((real, surr, float(r.min()), float(np.median(r)),
                         float(r.max())))
    for win in MANIFEST:
        z, c = fields[win.case]
        s = G.spectrum_matched_surrogate(z, c, seed=11)
        r = G.variogram(s, c).gamma_m2 / objs[win.case]["variogram"].gamma_m2
        fidelity.append((win.case, "(spot check)", float(r.min()),
                         float(np.median(r)), float(r.max())))
    return {"cases": cases, "replicates": reps, "objs": objs, "fields": fields,
            "cell_m": cell, "fidelity": fidelity}


def _safe_sa(ctx):
    try:
        return G.slope_area_relation(ctx=ctx)
    except ValueError:
        return None


def sweep_bake(args) -> dict:
    """Amplify a real 30 m window to 1.875 m with the real bake, and measure it."""
    from terrain_service.bake.pipeline import (
        BakeGeometry, CONSTANTS, bake_padded_domain, load_kernels,
    )

    # A CI-sized geometry: 128 coarse px of tile plus the production 32 px apron is a
    # 192 px padded coarse domain, i.e. 3072^2 fine cells at 1.875 m. The apron is the
    # production one because the whole point is to measure what the shipped bake makes.
    geom = BakeGeometry(coarse_tile_px=args.bake_coarse, coarse_pixel_m=30.0,
                        scale=16, apron_coarse_px=32)
    n = geom.padded_coarse_px
    win = {w.case: w for w in MANIFEST}[args.bake_case]
    z30, cell30 = fetch_window(win, max(args.size, n + 8), args.cache)
    coarse = np.ascontiguousarray(z30[:n, :n], dtype=np.float32)
    print(f"  baking {n}x{n} coarse -> {geom.padded_fine_px}^2 at "
          f"{geom.fine_pixel_m} m ...", flush=True)
    out = bake_padded_domain(coarse, world_seed=20260729, tile_x=0, tile_y=0,
                             kernels=load_kernels(), geom=geom, consts=CONSTANTS)
    sl = geom.interior()
    fine = geom.fine_pixel_m
    fields = {
        "coarse_input_30m": (coarse[32:-32, 32:-32].astype(np.float64), 30.0),
        "B0B1_carrier_rough": (np.asarray(out["carrier_plus_roughness"])[sl, sl]
                               .astype(np.float64), fine),
        "B3_baked": (np.asarray(out["z"])[sl, sl].astype(np.float64), fine),
    }
    ref = fields["B3_baked"][0]
    fields["fbm_at_1p875"] = (
        G.fbm(ref.shape, fine, hurst=0.75, seed=5, rms_m=float(ref.std())), fine)
    fields["surrogate_B3"] = (
        G.spectrum_matched_surrogate(ref, fine, seed=6), fine)

    cases, objs = {}, {}
    for name, (z, c) in fields.items():
        if name == "coarse_input_30m":
            continue  # different cell size: reported separately, never in the table
        print(f"  measuring {name} ...", flush=True)
        cases[name] = R.describe(z, c, search_m=args.search_m * fine / 30.0)
        ctx = G.flow_context(z, c)
        objs[name] = {"slope_area": _safe_sa(ctx), "variogram": G.variogram(z, c),
                      "hypsometry": G.hypsometry(z, c)}
    coarse_case = R.describe(*fields["coarse_input_30m"], search_m=args.search_m)
    return {"cases": cases, "objs": objs, "fields": fields,
            "coarse_case": coarse_case, "cell_m": fine,
            "interior_dead_ends": int(out["interior_dead_ends"])}


# --------------------------------------------------------------------------- output
def _tier_lines(name: str, vg) -> list:
    rows = G.tier_continuity(vg)
    if not rows:
        return [f"- `{name}`: variogram spans {vg.lag_m.min():.2f}-{vg.lag_m.max():.0f} m; "
                "no tier boundary falls strictly inside it."]
    out = []
    for r in rows:
        flag = " **KINK**" if r["kink"] else ""
        imp = " **H>1 (impossible)**" if r["impossible"] else ""
        out.append(
            f"- `{name}` at {r['boundary_m']} m: H below = {r['h_below']:.3f}, "
            f"H above = {r['h_above']:.3f}, ΔH = {r['delta_h']:+.3f}{flag}{imp}")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    default_cache = os.environ.get("GEOMORPH_CACHE") or os.path.join(
        os.path.expanduser("~"), ".cache", "voxelsim-geomorph")
    ap.add_argument("--sweep", default="earth",
                    choices=("earth", "bake", "all"))
    ap.add_argument("--source", default="copernicus", choices=("copernicus", "etopo"))
    ap.add_argument("--size", type=int, default=1024, help="window edge, cells")
    ap.add_argument("--search-m", type=float, default=300.0,
                    help="geomorphon lookout distance at 30 m")
    ap.add_argument("--cache", default=default_cache)
    ap.add_argument("--out", default=None, help="directory for plots and json")
    ap.add_argument("--markdown", default=None, help="write the report here")
    ap.add_argument("--replicates", action="store_true",
                    help="also measure each field's four quadrants, for the "
                         "within-class noise column of the separation table")
    ap.add_argument("--bake-case", default="alpine")
    ap.add_argument("--bake-coarse", type=int, default=128)
    ap.add_argument("--no-plots", action="store_true")
    args = ap.parse_args(argv)

    os.makedirs(args.cache, exist_ok=True)
    out_dir = args.out or os.path.join(args.cache, "out")
    os.makedirs(out_dir, exist_ok=True)

    md: list = [CONCLUSIONS] if args.sweep == "all" else []
    payload: dict = {}

    if args.sweep in ("earth", "all"):
        print("== earth sweep ==", flush=True)
        e = sweep_earth(args)
        payload["earth"] = {k: _jsonable(v) for k, v in e["cases"].items()}
        md += ["## Sweep 1 -- real Earth vs synthetic, all at "
               f"{e['cell_m']:.2f} m ({args.size}x{args.size} windows)", ""]
        md += [w.case.ljust(18) + " -- " + w.note for w in MANIFEST]
        md += ["", R.discrimination_table(e["cases"]), ""]
        md += ["", R.paired_contrast_table(
            R.paired_contrast(e["cases"],
                              [("alpine", "surrogate_alpine"),
                               ("fluvial_upland", "surrogate_fluvial")],
                              e["replicates"]),
            title="Question 1 -- does the metric see through a spectrum-matched fake?"),
            "",
            "Each fake has the same variogram as the real field beside it (see the "
            "fidelity table below), so anything that separates them is seeing "
            "structure the power spectrum does not contain. `worst fold` is the "
            "fractional gap on the *worse* of the two pairs; `worst gap/noise` divides "
            "that gap by the within-scene spread of the metric.", ""]
        if args.replicates:
            real_names = [w.case for w in MANIFEST]
            md += ["", R.separation_table(
                R.separation(e["cases"], e["replicates"], subset=real_names),
                title="Question 2 -- does the metric separate the five real terrain "
                      "classes? (within-class noise = the four quadrants of each "
                      "scene)"), ""]

        md += ["", "### Kink tolerance, calibrated", "",
               "`variogram.tier_continuity` flags a step in the local Hurst exponent "
               "as a tier-bookkeeping bug. These scenes have no tier boundary, so the "
               "change in local H across a lag in the middle of their range is the "
               "natural drift the tolerance has to clear:", ""]
        for name, o in e["objs"].items():
            vg = o["variogram"]
            mid = float(np.sqrt(vg.lag_m.min() * vg.lag_m.max()))
            rows = G.tier_continuity(vg, boundaries_m=(mid,), kink_tol=99.0)
            if rows:
                md.append(f"- `{name}`: ΔH = {rows[0]['delta_h']:+.3f} across "
                          f"{mid:.0f} m")
        md += ["### Is the surrogate a fair control?", "",
               "Ratio of the surrogate's semivariance to the original's, over every "
               "measured lag. A fair control sits near 1: it must be as rough as the "
               "terrain it is standing in for, or the metrics separate it for the "
               "wrong reason.", "",
               "| field | surrogate | min | median | max |",
               "|---|---|---|---|---|"]
        for real, surr, lo, mid, hi in e["fidelity"]:
            md.append(f"| {real} | {surr} | {lo:.2f} | {mid:.2f} | {hi:.2f} |")
        md += ["", "### Tier continuity (variogram)", ""]
        for name, o in e["objs"].items():
            md += _tier_lines(name, o["variogram"])
        md += [""]
        if not args.no_plots:
            _plots(e, out_dir, "earth")

    if args.sweep in ("bake", "all"):
        print("== bake sweep ==", flush=True)
        b = sweep_bake(args)
        payload["bake"] = {k: _jsonable(v) for k, v in b["cases"].items()}
        payload["bake"]["_coarse_input_30m"] = _jsonable(b["coarse_case"])
        md += [f"## Sweep 2 -- the real bake, at {b['cell_m']} m", "",
               f"Interior dead ends after routing: {b['interior_dead_ends']} "
               "(must be 0).", "",
               R.discrimination_table(b["cases"]), "",
               "The 30 m input window is measured too, but is reported here and not in "
               "the table above, because it is at a different cell size and the two "
               "are not comparable:", "",
               "```", json.dumps(_scalars(b["coarse_case"]), indent=2), "```", "",
               "### Tier continuity across the 30 m boundary", ""]
        for name, o in b["objs"].items():
            md += _tier_lines(name, o["variogram"])
        md += [""]
        if not args.no_plots:
            _plots(b, out_dir, "bake")

    text = "\n".join(md)
    print()
    print(text)
    if args.markdown:
        with open(args.markdown, "w", encoding="utf-8") as fh:
            fh.write(text + "\n")
        print(f"\n[wrote {args.markdown}]")
    with open(os.path.join(out_dir, "geomorph_validate.json"), "w",
              encoding="utf-8") as fh:
        json.dump(payload, fh, indent=1, sort_keys=True)
    return 0


def _plots(sweep: dict, out_dir: str, tag: str) -> None:
    sa = {k: v["slope_area"] for k, v in sweep["objs"].items() if v["slope_area"]}
    if sa:
        R.plot_slope_area(sa, os.path.join(out_dir, f"{tag}_slope_area.png"),
                          title=f"slope-area ({tag})")
    R.plot_variogram({k: v["variogram"] for k, v in sweep["objs"].items()},
                     os.path.join(out_dir, f"{tag}_variogram.png"),
                     title=f"variogram ({tag})")
    R.plot_hypsometry({k: v["hypsometry"] for k, v in sweep["objs"].items()},
                      os.path.join(out_dir, f"{tag}_hypsometry.png"),
                      title=f"hypsometry ({tag})")


def _scalars(d: dict) -> dict:
    return {k: (float(v) if isinstance(v, (int, float, np.floating, np.integer))
                and not isinstance(v, bool) else v)
            for k, v in d.items()
            if isinstance(v, (int, float, bool, np.floating, np.integer))}


def _jsonable(d):
    out = {}
    for k, v in d.items():
        if isinstance(v, (np.floating, np.integer)):
            v = v.item()
        if isinstance(v, (int, float, bool, str)) or v is None:
            out[k] = v
        elif isinstance(v, list):
            out[k] = v
    return out


