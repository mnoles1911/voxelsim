"""Validate `terrain_service.geomorph` against real Earth and against convincing fakes.

A metric that returns a number is worthless until it has been shown to separate the
cases we care about. This tool is that demonstration, and its output is
``terrain-service/docs/geomorph-validation.md``.

Three sweeps, each internally at **one** cell size, because slope, curvature, geomorphon
histograms and pit density all move with resolution and a table whose columns were
measured at different pixel sizes is worse than no table:

``--sweep earth`` (30 m)
    Five Copernicus GLO-30 windows -- alpine, dissected fluvial upland, high plains,
    sand sea, arid mountains -- against four synthetic controls: fBm with a plausible
    Hurst exponent, multi-octave value noise, a **phase-randomised surrogate of the
    alpine window itself** (identical power spectrum, no drainage), and the same window
    pixel-shuffled. The surrogate is the case that matters: it is the field that a
    spectral check cannot tell from real terrain.

``--sweep bake`` (1.875 m)
    A real 30 m window run through `bake.pipeline.bake_padded_domain` at a
    CI-sized geometry, measured at three points in the pipeline -- B0+B1 (carrier plus
    roughness, no erosion), the depression-filled surface, and the final B3 output --
    against an fBm control at the same 1.875 m. This is where the bake's own prediction
    ``theta = m/n = 0.5625`` is either met or not.

``--sweep tiers`` (1.875 m)
    Variogram of the baked surface across the 30 m tier boundary, to demonstrate what
    `variogram.tier_continuity` sees.

Reference data. ``terrain-service/tools/earth_reference.py`` is another agent's corpus
builder and is the right long-term source; at the time of writing it had not landed, so
this tool fetches its own windows straight from the Copernicus GLO-30 public bucket over
``/vsicurl`` and caches them as ``.npy``. ``--source etopo`` falls back to the local
``etopo_10m.tif``, which is real but 18 km/px and therefore useless for anything fluvial
-- it is there so the tool runs offline, not because its numbers mean much.

Determinism: every synthetic field is seeded explicitly, the window manifest is a
constant in this file, and nothing reads the clock. Re-running reproduces the table
byte for byte.
"""

