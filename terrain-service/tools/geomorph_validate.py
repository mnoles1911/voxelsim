# One arcsecond of latitude on the WGS84 ellipsoid, near enough everywhere for our
# purposes (30.87 m at the equator, 30.92 at 60 deg; we use the mean).
ARCSEC_M = 30.87


@dataclass(frozen=True)
class Window:
    """A named 1-degree GLO-30 tile plus a pixel window inside it."""

    case: str
    lat: int
    lon: int
    row0: int
    col0: int
    note: str


