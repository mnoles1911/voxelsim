// Prints biome.h's compile-time-derived thresholds as plain integers.
//
// worldgen.ush mirrors these BY HAND -- HLSL has no climate.h and no
// constexpr conversion -- so the literals in the shader have to come from
// somewhere trustworthy. Hand-arithmetic is exactly how a mirror drifts, so
// this prints them from the same headers the CPU path compiles against.
//
// Run it whenever biome.h's thresholds or climate.h's ranges change, and paste
// the output into worldgen.ush's constant block.

#include <cstdio>

#include "voxelcore/amplifier.h"
#include "voxelcore/biome.h"
#include "voxelcore/climate.h"

using namespace vxc;

int main() {
    std::printf("// ---- generated by vxc_dump_biome_constants; do not hand-edit ----\n");
    std::printf("static const int64_t kBiomeCliffSlopeMmPerPx = %lld;\n",
                (long long)kBiomeCliffSlopeMmPerPx);
    std::printf("static const int kBiomeBeachLowerMm = %d;\n", kBiomeBeachLowerMm);
    std::printf("static const int kBiomeBeachUpperMm = %d;\n", kBiomeBeachUpperMm);
    std::printf("static const int kBiomeTreelineBaseMm = %d;\n", kBiomeTreelineBaseMm);
    std::printf("static const int kBiomeTreelineMmPerTempUnit = %d;\n",
                kBiomeTreelineMmPerTempUnit);
    std::printf("static const int kBiomeAlpineRockLineMm = %d;\n", kBiomeAlpineRockLineMm);
    std::printf("static const int kBiomeTempColdU8 = %d;   // climateTempU8FromDegC(5)\n",
                kBiomeTempColdU8);
    std::printf("static const int kBiomeTempWarmU8 = %d;   // climateTempU8FromDegC(18)\n",
                kBiomeTempWarmU8);
    std::printf("static const int kBiomeTempHotU8 = %d;    // climateTempU8FromDegC(24)\n",
                kBiomeTempHotU8);
    std::printf("static const int kBiomePrecipAridU8 = %d;   // 400 mm/yr\n",
                kBiomePrecipAridU8);
    std::printf("static const int kBiomePrecipSemiU8 = %d;   // 800 mm/yr\n",
                kBiomePrecipSemiU8);
    std::printf("static const int kBiomePrecipModU8 = %d;   // 1600 mm/yr\n",
                kBiomePrecipModU8);
    std::printf("static const int kBiomeSeasonalHighU8 = %d; // bio_4 1500\n",
                kBiomeSeasonalHighU8);
    std::printf("\n// precipitation decode, for the topsoil formula:\n");
    std::printf("//   climatePrecipMmPerYrFromU8(u8) == (u8 * %lld) / 255\n",
                (long long)(kClimatePrecipMaxMmPerYr - kClimatePrecipMinMmPerYr));
    std::printf("\n// topsoil constants:\n");
    std::printf("//   base %d mm, %d mm per m/yr of rain, retain floor %d/1024,\n",
                200, 200, 128);
    std::printf("//   clamp [%d, %d] AFTER jitter\n", kVoxelSizeMm, 2500);
    return 0;
}
