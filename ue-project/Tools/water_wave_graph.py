DEG2RAD = math.pi / 180.0

# The two MPC_VoxelSky parameters this file wants from the weather subsystem.
# Kept as named constants because three places test them: the availability probe
# in build_wind_input, the error text it prints, and summary_lines().
WIND_VECTOR_PARAM = "WindVectorMS"
WIND_VALID_PARAM = "WindFieldValid"

# Number of octaves. NOT a parameter: it is the loop bound in the HLSL, the
# length of the spread table, and the thing the 1.42 frequency ratio was chosen
# against (eight octaves from a 5 m base end at 0.43 m, which is still four
# samples per wavelength on the 10 cm quantisation grid --
# create_water_voxel_material.py:2401-2413). Changing it is a design change in
# three places at once, so it is a constant and it is stated here.
OCTAVES = 8

# --- TWO CONSTANTS THAT DESCRIBE THE NORMALISED FIELD ---------------------
#
# "Normalised" = the octave sum with AmplitudeM factored out, i.e. what the loop
# produces before any gain. Both are needed and they are NOT interchangeable;
# conflating them is the mistake this file made first and it made the surf zone
# three times too wide.
#
# FIELD_CREST is the ABSOLUTE MAXIMUM the field can reach, and it is analytic
# rather than measured: the crest function exp(sin(x)-1)*0.5 peaks at exactly
# 0.5, the weights are normalised to sum to 1, and MEAN_WAVE is subtracted, so
# the bound is 0.5 - 0.2329 with every octave cresting at the same point. The
# trough bound is exp(-2)*0.5 - 0.2329 = -0.1652 by the same argument. Measured
# over 120 m x 120 m at four times: max 0.2450, min -0.1615 -- i.e. the field
# gets within 9% of a bound it can only reach when all eight octaves align.
# USED FOR: normalising H to [-1, 1]-ish for the crest test and the peaking.
FIELD_CREST = 0.2671

# FIELD_RMS is the standard deviation of the same field. Measured over
# 120 m x 120 m at four times, 900x900 samples: 0.0597.
# USED FOR: the wave HEIGHT, via the oceanographic definition of significant
# wave height, H_s = 4 * sigma. That is the number the breaker criterion wants,
# and using the crest instead (0.267 rather than 4*0.0597 = 0.239... which look
# similar, but the crest was being doubled to get a crest-to-trough height,
# giving 0.534) over-stated the wave by 2.2x and put the break line in water
# more than twice as deep as it belongs.
FIELD_RMS = 0.0597
HS_PER_RMS = 4.0

# THE CALIBRATION, AND IT IS BETTER THAN IT HAD ANY RIGHT TO BE. The shipped
# WaveAmplitudeM of 0.25 was set by eye against a slope-distribution
# measurement, with no reference to any wind at all
# (create_water_voxel_material.py:2358-2382). Put through H_s = 4 * sigma it
# comes out at 6.0 cm. The fetch-limited JONSWAP prediction for a 5 m/s wind
# over 500 m of open water is 5.7 cm. Those agree to 5%, and inverting the
# relation says the shipped lake is a 5 m/s breeze over 552 m of fetch -- which
# is a real, ordinary lake in a real, ordinary breeze.
#
# So WindRefSpeedMS = 5.0 is not an arbitrary pivot chosen to make the maths
# tidy. It is what the shipped water ALREADY IS, measured after the fact, and
# that is why the whole wind response is expressed as a ratio to it.
#
# ONE HONEST CAVEAT, RECORDED SO IT IS NOT DISCOVERED AS A SURPRISE: the
# amplitude matches the physics, the WAVELENGTHS DO NOT. JONSWAP puts the
# spectral peak for that wind and fetch at 1.15 m; the shipped base octave is
# 5.0 m, about 4x too long, and the eight octaves run 5.00 m down to 0.43 m
# around it. That was an artistic choice and it is kept -- this module supplies
# the SCALING with wind, not a re-tuning. The reason it does not look wrong is
# worth knowing: the shipped crest SPEED is 1.59 m/s (omega 2.0 on a 5 m
# wavelength), and the physically correct speed for the physically correct
# 1.15 m wave is 1.34 m/s. The lake moves at lake speed even though its crests
# are spaced further apart than a real one's.
SHIPPED_HS_CM = 6.0

# Where shoaling starts, in units of the break depth. Green's law says a wave
# arriving at its break depth from 4x that depth is 4^0.25 = 1.41x taller, so
# the ramp runs from xb = 4 down to xb = 1 and BreakShoalGain defaults to 0.4.
SHOAL_START_RATIO = 4.0

