"""The water surface's WIND-DRIVEN wave field, as one importable builder.

WHAT THIS IS. The eight-octave wave field that M_WaterVoxel already ships, with
three things added and nothing rebuilt: the wind STEERS it, the wind SIZES it,
and it BREAKS where the bed comes up. The node it authors still returns one
evaluation of one field, so the pixel normal and the vertex displacement cannot
disagree about where a crest is -- that property is the reason the existing
field is a single Custom node and it is preserved exactly
(create_water_voxel_material.py:2530-2632, "ONE evaluation, two outputs").

WHY IT IS A MODULE AND NOT MORE LINES IN create_water_voxel_material.py. That
file is 2964 lines and is regenerated by an automated chain; the wave field is
the part most likely to be iterated on and the part most likely to be wanted by
a second surface later (M_Ocean's implicit plane is the obvious candidate -- it
is a different material authored by create_ocean_material.py and today it has
its own unrelated ripple). This is the pattern the project already uses twice:
sky_star_graph.py owns the one star lookup that M_NightSky and
M_SkyAtmosphereDome share, and terrain_material_common.py owns the one biome
graph that M_VoxelTerrain and M_VoxelClipmap share. Both module docstrings make
the same argument, which is worth restating because it is the whole reason:
TWO COPIES OF ONE DERIVATION DO NOT FAIL LOUDLY. They drift, and the result is
still sharp, still animated, still plausible, and wrong, with nothing in a frame
to say so.


=============================================================================
THE ARCHITECTURAL SPLIT THIS FILE SITS ON
=============================================================================

Fast waves are a SURFACE effect. Slow water-level change is a SIMULATION
effect. This file is entirely the first one and deliberately touches none of
the second.

THE NUMBERS BEHIND THAT, because it was put as a question and deserves an
answer with arithmetic in it rather than a preference:

  * A wind chop of 20 cm crest-to-trough is TWO VOXELS on a 10 cm grid. Driven
    through the cellular automaton it cannot be a wave, it can only be a
    two-step staircase that flips on and off -- and the CA's fill fraction is
    quantised again on top of that (vertex colour R is fill 0..255 remapped,
    create_water_voxel_material.py:14-18). The surface path has no such floor:
    World Position Offset moves a vertex by a float, and the shipped
    displacement is +/-2.1 cm, a FIFTH of a voxel. The effect being asked for is
    strictly below the simulation's resolution and strictly above the
    material's.
  * Driving it through the CA means touching every water cell every frame
    across 2,049 basins, to produce something no cell can represent.
  * The wave field is evaluated where it is seen -- on drawn water surface
    pixels and vertices, at the shading rate, and at zero cost for the whole
    submerged volume and for every basin off screen.

WHAT GENUINELY BELONGS IN THE SIM, AND THE HOOK FOR IT, since it came up in the
same breath and should not be lost: a slow, basin-wide change to the water LEVEL
-- tide, seiche, storm surge -- moves the waterline and wets new ground, and no
surface effect can do that. The clean hook is `SurfaceZUU`, the per-basin drawn
water surface (VoxelWaterSubsystem.h:486, :633). Everything downstream already
keys off it: the sheet's hole test (`HasMobilizedWaterInImplicitDisc(double
SurfaceZUU)`, :552) and the basin extent masks (:502-560) both take it as an
argument rather than reading a constant. A slow offset added at that one site
would move the drawn surface, the wet extents and the despawn masks together.
NOT DONE HERE and not designed here -- flagged because the site is unusually
clean and somebody will want it.

That hook is also the reason this file does NOT try to fake a tide by lifting
the wave field's mean: the extents would not follow, so the lake would grow a
lip standing proud of its own shoreline.


=============================================================================
THE WIND INTERFACE -- WHAT THIS FILE NEEDS FROM THE WEATHER SUBSYSTEM
=============================================================================

TWO MPC_VoxelSky PARAMETERS, and the shapes are chosen so that they cannot be
inconsistent with each other:

  WindVectorMS  (vector)  R = wind velocity along world +X, metres per second
                          G = wind velocity along world +Y, metres per second
                          B = reserved for a gust factor (unread today)
                          A = unused
                          Default (0,0,0,0) = dead calm.

  WindFieldValid (scalar) 1 once the weather field has published this run, 0
                          otherwise. Default 0.

ONE VECTOR, NOT A DIRECTION AND A SPEED. Direction and speed as two parameters
can disagree -- a unit vector left stale next to a speed that moved is a wind
that blows the wrong way, and nothing in a frame reports it. A velocity vector
cannot be inconsistent with itself, and it makes "calm" exactly one value
(zero) rather than a special case someone has to remember to write. The
material recovers speed as `length()` and direction as the normalised vector,
which is three instructions.

DIRECTION SENSE, STATED EXPLICITLY BECAUSE METEOROLOGY AND VECTORS DISAGREE ON
IT AND THIS IS THE CLASSIC 180-DEGREE BUG: WindVectorMS is a VELOCITY. It
points where the air is GOING. A "northerly" in the forecast sense blows FROM
the north, so in this world's frame (VoxelEphemeris.h:44-48 fixes X = north,
Y = east, Z = up) a 6 m/s northerly is WindVectorMS = (-6, 0, 0, 0). Waves in
this file travel along +WindVectorMS.

SPEED REFERENCE HEIGHT: the standard 10 m (U10). Every fetch/growth relation
quoted below is written for U10 and the defaults were calibrated against it. If
the weather field publishes a surface-level or a boundary-layer wind instead,
say so and the calibration moves -- it does not silently absorb.

WHY MPC_VoxelSky AND NOT A NEW COLLECTION. The far-field lake sheet
deliberately has no dynamic material instance (VoxelWaterSheetActor.h:47-52),
so an MPC is the only CPU->material channel that reaches both water draw paths.
This material already binds six parameters on that collection (SunDirection,
MoonDirection, MoonLightFraction and the three bathymetry ones); a seventh costs
nothing and keeps the "one collection, one author" rule that
create_sky_material.py enforces by deleting and recreating the asset every run.
A SECOND collection would be a second thing that can be regenerated out from
under a dependent, which is a failure this project has already paid for once
(2026-08-10, every dependent binding compiling to the ENGINE DEFAULT MATERIAL
while the log said success -- create_water_voxel_material.py:460-465).

IT RUNS TODAY WITHOUT ANY OF THAT. `build_wind_input` reads the collection's
parameter list back and, if the two names are absent, silently drops to two
MATERIAL parameters (WindFallbackSpeedMS, WindFallbackDirDeg) whose defaults
reproduce the shipped look. This is deliberate and it is not laziness: the two
halves of this feature are being built by two people at once, and a wave module
that cannot be generated until the weather subsystem lands is a module that
gets tested for the first time on the day both land. The fallback is also the
runtime path whenever WindFieldValid is 0, so a session with the weather
subsystem disabled gets today's lake rather than a glassy one.


=============================================================================
THE MODEL
=============================================================================

WIND SIZES THE WAVES: FETCH-LIMITED, NOT FULLY DEVELOPED. This matters and it
is the one place where reaching for the famous formula gives the wrong answer
by an order of magnitude.

The Pierson-Moskowitz relations everyone quotes describe a FULLY DEVELOPED sea
-- open ocean, wind blowing over unlimited water for long enough to saturate.
They give, at 5 m/s, a significant wave height of 0.61 m and a peak wavelength
of 20.8 m. On a 500 m lake that is absurd: it is a wave taller than the shallows
and longer than a tenth of the basin.

The right family is the fetch-limited JONSWAP set (Hasselmann et al. 1973),
which adds the distance the wind has blown over water:

    H_s   = 1.6e-3 * U * sqrt(F / g)                 significant wave height
    f_p   = 3.5 * (g / U) * (g F / U^2)^(-0.33)      peak frequency
    lam_p = g / (2 pi f_p^2)                         deep-water wavelength

At U = 5 m/s over F = 500 m of fetch: H_s = 5.7 cm and lam_p = 1.1 m. THAT is a
lake, and 5.7 cm is within spitting distance of the 7.6 cm maximum height the
shipped field was independently tuned by eye to produce. The tuning was right;
this file is only giving it a handle.

WHAT IS ACTUALLY IMPLEMENTED IS THE EXPONENTS, NOT THE FORMULAE, and the reason
is that fetch is not available in the material. It would be: a lake's fetch in
the wind direction is a distance-to-shore query along a ray, and the baked
bathymetry has a distance-to-shore field -- but it is the distance to the
NEAREST shore, not the distance upwind, and a ray march per pixel to get the
right one is not affordable. So fetch is folded into the calibration constant
and only the SCALING with wind speed is kept:

    at fixed fetch,  H   proportional to U^1.00      (from H_s above)
                     lam proportional to U^0.68      (f_p ~ U^-0.34, lam ~ f^-2)

Both are exposed (WindAmpExponent, WindLenExponent) and both are quoted against
a reference speed, so "wind of WindRefSpeedMS reproduces the field that is
shipped today" is true by construction and is the calibration constant. Set the
reference to 5 m/s (the default) and the exponents describe how a lake behaves
either side of a moderate breeze.

Both are exact-1.0 multipliers at U = WindRefSpeedMS, which is what makes the
regression check below possible.

THE WAVES ALSO MOVE FASTER IN MORE WIND, AND IT IS FREE. Deep-water gravity
waves obey omega = sqrt(g k), so a longer wave oscillates more slowly but its
crests travel faster: c = omega/k grows as sqrt(lambda). The base octave's
angular frequency is therefore scaled by sqrt(BaseWavelengthM / lambda0), which
is 1.0 at the reference speed and about 1.3 at a 20 m/s storm. The per-octave
time multiplier progression (1.07) is UNCHANGED and is deliberately NOT the
dispersion-correct 1.19 -- it is what the shipped field looks like, and
switching to true dispersion is a look change that should be made on its own
and judged on a capture, not smuggled in under a wind feature.


WIND STEERS THE WAVES: A CONE, NOT A LINE, AND NOT A CIRCLE.

The shipped field spreads its eight octaves over the WHOLE circle with a
golden-angle increment (137.507764 deg). That was the correct fix for the
problem it was solving -- a corduroy lake with every wavefront on a world axis
-- but as a description of a wind sea it is wrong in a specific way: it is a
CONFUSED sea, with as much energy travelling upwind as downwind. Real wind seas
are directionally spread AROUND the wind vector, and the spread is narrow at the
spectral peak and broad in the high-frequency tail (Mitsuyasu's cos^2s model,
with the spreading exponent s largest at the peak). That is a fact worth using
rather than a detail: it means the LONG, HEAVY octaves line up with the wind and
the short ones fan out, which is exactly what makes a windy lake look like
long streaks with fine texture scribbled across them.

So octave i is placed at

    angle_i = baseAngle + lerp(i * DirIncrementDeg,
                               WindSpreadDeg * SPREAD_SHAPE[i],
                               WindDirectionAuthority)

with SPREAD_SHAPE a fixed eight-element sequence, generated once in
`octave_spread_shape()` and injected into the HLSL from there so the Python and
the shader cannot hold two different tables. Its two properties:

  * A GOLDEN-RATIO LOW-DISCREPANCY SEQUENCE mapped to [-1, +1], so the eight
    directions cover the cone evenly without any two being equal and without a
    pattern that repeats. Sampled as frac((i + 0.5) * phi) rather than
    frac(i * phi) specifically so that NO octave gets an offset of exactly zero
    -- an octave sitting precisely on the wind axis is the one direction the
    whole set should not contain, for the same reason WaveDirBaseDeg is not 0
    (create_water_voxel_material.py:2431-2452).
  * A WIDTH THAT GROWS WITH OCTAVE INDEX, 0.5x at the longest octave to 1.5x at
    the shortest. This is the Mitsuyasu behaviour above, and it is also the
    insurance against the failure mode this change could introduce: eight nearly
    parallel octaves is corduroy again. At the default WindSpreadDeg = 35 the
    eight offsets are

        -6.7, +19.2, +2.5, -21.9, +21.1, -8.6, -45.9, +14.2  degrees

    i.e. the peak octave is within 7 degrees of the wind and the tail reaches
    46 degrees off it.

WindDirectionAuthority is the blend between the old whole-circle placement (0)
and the wind cone (1), and it exists for exactly one reason: at 0 this module
reproduces the shipped field. See THE REGRESSION RECIPE below.

THE BASE ANGLE IS BLENDED WITH ITS WRAP REMOVED. `dA -= 2pi * round(dA / 2pi)`
before the lerp, so a wind rotating through the 359 -> 1 degree boundary does
not swing the whole field the long way round at intermediate authorities. At
authority 0 or 1 the term is unreachable; it is one instruction and it removes
a class of bug that would only appear on a slowly-turning wind.

AND THE ANGLE NAMES THE WAVEFRONT'S UPWIND NORMAL, NOT THE TRAVEL DIRECTION.
This is a convention inherited from the shipped loop, kept because changing it
would break bit-exact reproduction, and it is written down here because it is
the kind of thing that gets "fixed" into a 180-degree error. In
`x = dot(d, pos) * freq + T * tmul`, a crest sits where x is constant, so as T
grows `dot(d, pos)` must fall: THE WAVE TRAVELS ALONG -d. The wind target angle
is therefore the wind bearing plus 180 degrees, applied as `atan2(-w.x, -w.y)`,
which puts the travel direction on +w -- downwind, where it belongs.


CALM AND CHOPPY PATCHES: ALREADY THERE, NOW BLOWN DOWNWIND. The shipped field
already multiplies everything by a very-low-frequency amplitude field (two
diagonal sines at ~180 m and ~232 m, non-commensurate with each other and with
every octave -- create_water_voxel_material.py:2520-2528). That requirement is
met by code that exists, so it is kept verbatim rather than replaced, and one
thing is added: the patch field is now advected by the wind, so gust cells drift
downwind instead of sitting still and merely breathing. Cost is one multiply-add
on the sample position. WindPatchDriftFrac defaults to 0.5 -- real gust cells
travel at close to the mean wind, but at 1.0 a 10 m/s wind sweeps the whole
patch structure past a fixed viewpoint in about 20 seconds, which reads as the
lake sliding rather than as the wind gusting.


=============================================================================
BREAKING, AND WHY IT SHARES ONE NUMBER WITH THE SHORE DAMPING
=============================================================================

THE CRITERION. A wave breaks when the water gets shallow enough relative to its
own height. The classic solitary-wave result (McCowan) is a breaker index
H/d = 0.78 at the break point, i.e. it breaks once the depth falls below
1.28 * H. That ratio is the default (BreakDepthRatio = 1.28) and it is the whole
criterion; nothing here integrates a shoaling wave properly, and nothing needs
to.

THE COLLISION WITH THE EXISTING SHORE DAMPING, AND TWO WRONG ANSWERS BEFORE THE
RIGHT ONE. Both wrong answers were caught by the offline probe rather than by
reasoning, which is the only reason this section is short.

The material already damps wave amplitude to zero as the bed comes up -- a
linear ramp over the first BathyWaveDampDepthM = 0.6 m of depth
(create_water_voxel_material.py:2596-2617). The break depth for the SHIPPED wave
is 1.28 * 6.0 cm = 7.7 cm. So the two numbers are not merely in tension, they
are a factor of EIGHT apart, and the damping wins: a wave arrives at the depth
where it ought to break with 16% of its height left. There is almost nothing
there to break.

WRONG ANSWER 1: collapse them into ONE band, `dSurf = max(1.28*H_s, 0.6)`, with
breaking as the exact complement of the damping. Elegant, and wrong twice. At
ordinary wave heights that band is set by the 0.6 m floor rather than by the
breaker, so it foams the WHOLE 0.6 m band whenever there is any wave at all --
measured, a 3 m/s breeze foamed out to 46 cm of depth, which is the permanent
white ring the gates below exist to prevent. And it foams water the wave is not
breaking in: being damped and being broken are different things.

WRONG ANSWER 2: nest them, `dBreak = 1.28*H_s` inside `dSurf = max(dBreak, 0.6)`,
and drive the foam off the inner band only. That fixes the ring -- foam appears
only in the last 9.8 cm of depth at 5 m/s -- and it leaves the original defect
completely untouched. Measured on a 2-D shore at four phases, peak crest height
inside the foamed region:

                        5 m/s     12 m/s
    dSurf floored 0.6   1.22 cm   5.62 cm     amplitude at the break line 16% / 47%
    dSurf floored 0.15  4.88 cm  12.95 cm     amplitude at the break line 65% / 100%

A correct-looking foam mask over water with a quarter of its wave in it.

AND A CORRECTION TO HOW THAT WAS FIRST WRITTEN DOWN, because the first version of
this comment recorded the defect as "the peaking term measures +0%", which is
false and was an artefact of the probe (see the note at the end of this section).
The peaking RATIO is amplitude-independent -- it is a shape function, and it
measures x1.70 at 5 m/s under BOTH configurations. What the floored band destroys
is the ABSOLUTE crest, four-fold. The conclusion did not change; the evidence for
it did, and quoting the wrong quantity would have sent the next person looking at
the peaking maths instead of at the band width.

THE ANSWER IS THAT THE DAMPING BAND WAS THE WRONG SIZE, not that the breaking
needed a different band. A real surf zone runs FROM the break point TO the
waterline; the wave keeps its height until it breaks and then dissipates. So the
two bands are the same band:

    dBreak = BreakDepthRatio * H_s               the wave breaks here
    dSurf  = max(dBreak, BreakSurfFloorM)        the wave dies over this

    shore damping = saturate(depth / dSurf)      1 offshore, 0 at the waterline
    breaking      = 1 - saturate(depth / dBreak)

and BreakSurfFloorM (0.15 m, 1.5 voxels) is a floor for tiny waves only, so that
a near-flat lake still fades in rather than stopping dead at the shoreline.
Above about 12 cm of wave the two coincide exactly and the breaking is the
literal complement of the damping.

THE BAND IS PROPORTIONAL TO THE WAVE, AND THAT IS WHAT MAKES IT BEHAVE AT BOTH
ENDS. At zero wind H_s is exactly 0, dBreak is 0, and there is no surf zone at
all -- calm water laps a shore silently, with no ring. At 20 m/s, H_s is 24 cm
and the surf reaches 31 cm of depth, which on a 1-in-20 beach is a six-metre
band of white. THE SURF ZONE WIDENS WITH THE WIND, free.

AND IT HANDS BACK A GUARANTEE THAT USED TO BE A GUESS. Inside the surf zone a
linear ramp on a wave-proportional band makes the wave DEPTH-LIMITED at any wind
speed -- H(d) is proportional to d with a coefficient near 1, which is exactly
what a real surf zone does and is why a beach looks the same in a gale as in a
breeze except wider. Measured over a 0.8 m -> 0 m shore at four phases, crest
height as a fraction of local depth:

              U = 2 m/s   5 m/s   10 m/s   20 m/s
    p99          0.17     0.50     0.75     0.75
    max          0.28     0.75     1.22     1.22
    GEOMETRY     0.07     0.19     0.30     0.30    (the 0.25 WPO fraction)

so the VERTEX DISPLACEMENT never exceeds about a third of the water it is
standing in, at any wind speed, and it stops growing above 10 m/s because the
depth limit has taken over. That is the concern that pinned WaveWpoFraction at
0.25 in the first place (create_water_voxel_material.py:2385-2398, "no
shore-damping term to stop a rising crest clipping through its own bank"),
answered with a bound instead of a small number. The fraction could now be
raised on evidence; it is NOT raised here, because that is a look change and the
owner judges those from captures.

The shading field's rarest crests do exceed the local depth (max 1.22 at
10 m/s). That is a normal and a colour, not geometry -- it cannot clip anything
-- and it is left alone rather than clamped, because clamping it would flatten
exactly the crests a breaking wave is supposed to have.

HOW ALL OF THE ABOVE IS MEASURED, AND THE ONE THAT WAS MEASURED WRONG. The
offline probe originally sampled the shore as a single 1-D LINE -- 601 points,
depth 3 m -> 0 across 30 m, y fixed. At 12 m/s that puts the entire surf zone in
54 samples spanning 2.70 m of x, which is 0.30 of ONE 9.07 m wavelength: a third
of a wave, at whatever phase the line happened to cross. The mask it then applied
(`breaking > 0.2`) selects the samples nearest the WATERLINE, where the swash
term takes foam to 1 whatever the crest is doing -- and in that particular strip
every one of them was trough, H from -1.34 to -0.00 cm. So it computed "crest
amplification" over a set containing no crests and printed x1.00, i.e. it
reported a working effect as doing nothing. The fifteen samples that DID carry a
crest sat further out where breaking is 0.000..0.076, below the mask.

THE FIX WAS PHASES, NOT RESOLUTION. A 2-D shore -- 16 m across x by 40 m along y
at 320x800, four times -- samples every depth at ~800 phases instead of one, and
the same module then measures +9 to +11% crest and x1.50..x1.83 gradient. A
1-D transect through a 2-D random field cannot resolve a phase-conditioned
statistic however finely it is sampled, and the failure is silent: it returns a
plausible small number rather than an error.

THE COST OF THIS, STATED PLAINLY: waves now reach the shore, where before they
faded out 60 cm deep. That is the feature, and it is a VISIBLE change to shipped
behaviour rather than a pure addition. The regression recipe sets
BreakSurfFloorM back to 0.6 and restores the old damping exactly.

THREE GATES ON THE FOAM, because a permanent white ring around a still lake is
the single most recognisable tell of a tutorial water shader and this file is
one line away from drawing one (the same discipline, and the same sentence, as
the shoreline foam already in the material at
create_water_voxel_material.py:1288-1296):

  1. SIZE. `saturate(H_s / BreakMinWaveHeightM)`, default 5 cm. An absolute
     floor underneath the proportional band above -- belt and braces, and it is
     the gate that survives if somebody later gives dBreak a floor of its own.
  2. CREST. Foam appears on the CRESTS of the field, not uniformly across the
     band: `saturate((h / peak - BreakCrestThreshold) / (1 - ...))`. Because the
     crests travel, the foam travels with them, which is what makes it read as
     surf rather than as a painted stripe. The threshold relaxes to zero at the
     waterline (`lerp(crest, 1, band)`) because the swash really is continuous
     foam by the time it reaches the sand.
  3. VALIDITY. Multiplied by the bathymetry field's validity, like every other
     consumer -- bathy_field_graph.py:26-40 lists the three independent ways the
     field is absent and folds them into that one number. Where there is no
     baked depth there is no breaking, and the water looks exactly as it does
     today.

THE PEAKED SHAPE. A shoaling wave pitches forward: the crest sharpens and rises
while the trough stays broad. Applied as a shaping function on the height,

    f(H) = H + k * max(H, 0)^2 / peak,      k = BreakPeakGain * breaking

which lifts crests, leaves troughs untouched, and -- the part that matters here
-- has an ANALYTIC derivative, f'(H) = 1 + 2k*max(H,0)/peak, which is applied to
the gradient in the same three lines. The normal and the displacement stay two
outputs of one field. That is the property this whole node exists to have, and a
crest sharpening that only moved the geometry would quietly break it.

  APPROXIMATION, STATED: the exact gradient of f(H(p)) would also carry
  dk/dp -- the spatial variation of the breaking signal itself. It is left out,
  for the same reason and with the same honesty as the patch field's derivative
  already is (create_water_voxel_material.py:2526-2528): the breaking signal
  varies over the width of the surf band, metres, while the wave varies over
  tens of centimetres, so the omitted term is smaller by that ratio.

SHOALING GAIN. Waves grow before they break -- Green's law gives H ~ d^(-1/4) in
shallow water, so a wave arriving at its own break depth from four times that
depth is 4^0.25 = 1.41x taller. That is approximated with a linear ramp over
xr in [1, 4] reaching BreakShoalGain = 0.4 at the break line. It is deliberately
a ramp rather than the exact power law: the power law diverges at zero depth,
and the honest fix for that is a cap, at which point the cap is the model.


=============================================================================
THE REGRESSION RECIPE
=============================================================================

This module reproduces the shipped field EXACTLY -- not approximately -- with

    WindDirectionAuthority = 0        (whole-circle golden-angle placement)
    WindVectorMS length    = WindRefSpeedMS   (so both wind scalings are 1.0)
    BreakShoalGain         = 0
    BreakFoamGain          = 0
    BreakPeakGain          = 0

`LEGACY_RECIPE` below is that list in machine-readable form. Verified offline
against a numpy transcription of both the shipped HLSL and this one over a
30 m x 30 m patch at 400x400 samples, at the world's real ~84 km offset:
MAXIMUM ABSOLUTE DIFFERENCE 5.1e-11 m in height and 8.6e-10 in the gradient
components -- float64 rounding from re-associating the angle accumulation into
a lerp, i.e. the same field. Tilt statistics identical to two decimal places
(p50 2.91, p95 5.98, p99 7.36, max 11.24 degrees).

The point of that is not the number, it is that any future change to this file
shows up as a diff of the WAVE against a baseline that is a PARAMETER SET rather
than a git revision of a 2964-line generator.

The one thing the recipe does NOT restore is the direction of drift: nothing
here changes it, and nothing needed to -- the octave loop's sign convention is
untouched, which is why the difference above is 1e-11 and not a mirror image.


=============================================================================
COST
=============================================================================

ESTIMATED, NOT MEASURED, and the distinction is not a formality: nothing in this
change can be compiled without an editor, and this file was authored while the
editor was held by another job. The estimate is an operation count of the
emitted HLSL, which is what the shader compiler starts from and not what it
finishes with.

    shipped WaveField node        ~150 instructions (8 octaves x ~15, plus the
                                  patch field and the assembly)
    + wind sizing                 ~12   (length, normalize, 2 pow, 1 sqrt)
    + wind steering               ~30   (1 atan2, 1 round, 8 x lerp+mul)
    + patch advection             ~4
    + surf band and shoaling      ~12
    + breaking signal             ~14
    + crest peaking               ~8
    ------------------------------------------------------------------------
    estimated total               ~230 instructions

Two things about that number. It is a PIXEL AND VERTEX cost on water surfaces
only -- the node feeds MP_NORMAL and MP_WORLD_POSITION_OFFSET, so it runs once
per water vertex and once per water pixel and never for the submerged volume or
for basins off screen. And roughly 80 of the added instructions are wind
steering and sizing, which are UNIFORM ACROSS THE DRAW: they depend only on
material parameters and collection parameters, not on position, so a compiler
that hoists uniform expressions will move most of them out of the loop body.
Whether this one does is exactly the sort of claim this project does not make
without a measurement, so it is written as a hope and not as a result.

WHAT WAS DELIBERATELY NOT DONE, listed so nobody looks for it: no gust term (the
B channel of WindVectorMS is reserved and unread), no per-octave distance fade,
no true dispersion in the per-octave time progression, no fetch query, no
foam texture, and no change of any kind to the simulation.
"""

