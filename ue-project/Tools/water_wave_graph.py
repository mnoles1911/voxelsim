def _custom_node(b, name, code, inputs, output_type):
    """A MaterialExpressionCustom with named inputs and no wiring yet.

    A copy of create_water_voxel_material.py:692-714 in shape, and it has to be:
    only the input NAME is settable from Python -- FCustomInput carries an FName
    and an FExpressionInput, and the FExpressionInput is filled in by the
    connect calls that follow. So the array is built name-only here and the
    caller wires it with the usual checked link().
    """
    node = b.node(unreal.MaterialExpressionCustom)
    node.set_editor_property("description", name)
    node.set_editor_property("code", code)
    node.set_editor_property("output_type", output_type)
    ins = []
    for nm in inputs:
        ci = unreal.CustomInput()
        ci.set_editor_property("input_name", nm)
        ins.append(ci)
    node.set_editor_property("inputs", ins)

    # READ THE NAMES BACK. set_editor_property on a TArray of structs is the
    # least-exercised call in this whole toolchain -- create_sky_material.py
    # verifies its MPC parameter array the same way and for the same reason
    # (create_sky_material.py:598-605). A dropped input name here would not fail
    # to compile: the HLSL would reference an undeclared symbol and the material
    # would go to the default, which on this project has already cost a session.
    got = [str(ci.get_editor_property("input_name"))
           for ci in node.get_editor_property("inputs")]
    if got != list(inputs):
        raise RuntimeError(
            "Custom node %r input names did not round-trip: wrote %s, read back %s"
            % (name, list(inputs), got))
    return node


def build_wind_input(b, defaults=None, log=None):
    """The wind velocity as a float2 in m/s, world XY. Returns (expr, source).

    `b` must be a SkyGraphBuilder (sky_star_graph.py:146) -- this needs its
    CHECKED collection_param and its mpc_names read-back, for the reason that
    module states at length: an unresolved CollectionParameter compiles to a
    CONSTANT rather than failing (MaterialExpressions.cpp:17179-17193), so a
    typo would ship a lake with a permanent imaginary wind and no diagnostic.

    TWO SOURCES, AND THE FALLBACK IS NOT A STUB.

      * MPC_VoxelSky.WindVectorMS, blended in on MPC_VoxelSky.WindFieldValid.
        This is the weather subsystem's channel; see the module docstring for
        the exact semantics both halves have to agree on.
      * Two MATERIAL parameters, WindFallbackSpeedMS and WindFallbackDirDeg,
        used when the collection has no wind parameters at all AND (at runtime)
        whenever WindFieldValid is 0.

    THE FALLBACK IS THE RUNTIME PATH FOR A SESSION WITH NO WEATHER, not merely a
    build-time convenience, which is why its defaults reproduce the shipped
    look: 5 m/s at a bearing whose upwind normal is 58.7 degrees -- the swept
    optimum the shipped field already uses (the sweep, and why 0 would be a bug,
    is at create_water_voxel_material.py:2431-2452).

    IF THE COLLECTION HAS NO WIND PARAMETERS THIS DOES NOT RAISE, which is a
    deliberate departure from how every other binding in this toolchain behaves.
    Everywhere else a missing MPC parameter is a hard error, because it means a
    generator ran out of order. Here it means the OTHER HALF OF THIS FEATURE HAS
    NOT LANDED YET -- the weather subsystem and this module are being built at
    the same time -- and a water material that refuses to generate until then is
    a material whose first test is the day both land. It logs, loudly, and takes
    the fallback.
    """
    d = dict(DEFAULTS)
    if defaults:
        d.update(defaults)

    # --- the fallback, always built ----------------------------------------
    #
    # WindFallbackDirDeg is the bearing of the wind VELOCITY -- where the air is
    # going -- in the same angle convention the wave loop uses for its octave
    # directions: the unit vector is (sin a, cos a) in world XY, i.e. a is
    # measured from world +Y toward world +X.
    #
    # THE DEFAULT LOOKS ARBITRARY AND IS NOT. 238.7 = 58.7 + 180, so the upwind
    # normal this produces is exactly 58.7 degrees, the angle
    # create_water_voxel_material.py swept for: the base angle that maximises
    # the smallest distance between any octave's wavefront and a world axis. The
    # fallback lake therefore has its dominant wave train pointing where the
    # shipped lake's does.
    fb_speed = b.scalar("WindFallbackSpeedMS", d["WindFallbackSpeedMS"])
    fb_dir_deg = b.scalar("WindFallbackDirDeg", d["WindFallbackDirDeg"])
    fb_ang = b.mul(fb_dir_deg, b.const(DEG2RAD))
    # b.sine/b.cosine, NOT raw Sine/Cosine nodes: those default to Period = 1.0
    # and silently compute sin(2pi*x), multiplying every angle by 6.283 with no
    # error anywhere. SkyGraphBuilder._trig sets the period and reads it back --
    # sky_star_graph.py:249-276 lists the two shipped bugs that cost.
    fb_dir = b.append(b.sine(fb_ang), "", b.cosine(fb_ang), "")
    fallback = b.mul(fb_dir, fb_speed)

    names = b.mpc_names()
    have = WIND_VECTOR_PARAM in names and WIND_VALID_PARAM in names
    if not have:
        msg = ("[water_wave_graph] MPC_VoxelSky has no %s / %s -- building the water "
               "wave field on its MATERIAL fallback wind (%s m/s at %s deg). This is "
               "the expected state until the weather subsystem publishes those two "
               "parameters from create_sky_material.py's VECTOR_PARAMS / "
               "SCALAR_PARAMS. Present on the collection: %s"
               % (WIND_VECTOR_PARAM, WIND_VALID_PARAM,
                  d["WindFallbackSpeedMS"], d["WindFallbackDirDeg"], sorted(names)))
        (log or print)(msg)
        return fallback, "material-fallback"

    wind_mpc = b.mask(b.collection_param(WIND_VECTOR_PARAM), "", r=True, g=True)
    wind_valid = b.collection_param(WIND_VALID_PARAM)
    # Lerp and not a select: WindFieldValid is written by C++ and a hard switch
    # at 0/1 would pop the whole lake's wave direction the frame the weather
    # subsystem starts publishing. A CPU-side ramp on that scalar makes the
    # handover a fade for free.
    return b.lerp(fallback, "", wind_mpc, "", wind_valid), "MPC_VoxelSky"


def build_wave_field(b, pos_m, time_expr, bathy, defaults=None, log=None):
    """The whole wave field. Returns a dict of expressions.

    Arguments:
      b          a SkyGraphBuilder bound to the material and to MPC_VoxelSky.
      pos_m      float2, the sample position in METRES. Must be ABSOLUTE world
                 XY -- see below; this is not a detail the caller may vary.
      time_expr  the scalar time driving the field. Passed in rather than
                 created here so create_water_voxel_material.py's
                 VOXEL_WATER_FREEZE_TIME arm stays a single-node substitution
                 (create_water_voxel_material.py:503-533): freezing that one
                 node still provably freezes every animated term on the surface,
                 including the breaking foam, which now also rides it.
      bathy      the dict from bathy_field_graph.sample_bathy_field(b). Read for
                 `depth_m` and `validity` ONLY -- the shoreline foam's use of
                 `shore_m` is a different effect and stays where it is.

    Returns keys:
      node       the Custom node itself
      gradient   float2, dH/dx and dH/dy, for the normal
      height_m   float, metres, for the World Position Offset
      breaking   float 0..1, for foam
      wind       the float2 wind velocity expression, in case a caller wants it
      wind_source  "MPC_VoxelSky" or "material-fallback"

    THE POSITION MUST BE ABSOLUTE WORLD XY AND THE CALLER OWNS THAT. It is the
    single most important line in the shipped section and the argument is long
    (create_water_voxel_material.py:2303-2320, "CAUSE A"): the pooled vertex
    factory's UV repeats every 32 m and mirrors about x=0 and y=0, and the
    far-field sheets anchor their UV at each sheet's own bounding-box corner, so
    near water and far water had unrelated wave phase and met at a seam. World
    XY is the only coordinate both draw paths can agree on and it has no period.
    It is also what makes adjacent bricks compute bit-identical displacement at
    a shared vertex, which is the only thing stopping the mesh tearing open along
    every seam as the phase moves.
    """
    d = dict(DEFAULTS)
    if defaults:
        d.update(defaults)

    wind, wind_source = build_wind_input(b, defaults=d, log=log)

    node = _custom_node(b, "WaveField", wave_code(), WAVE_INPUTS,
                        unreal.CustomMaterialOutputType.CMOT_FLOAT4)

    # Every pin, wired by name, every connect checked. SkyGraphBuilder.link
    # raises with the destination's actual pin list on failure, which is the
    # fastest way to find the one cause these ever have (a name).
    wiring = [
        ("PosM", pos_m),
        ("T", time_expr),
        # --- the shipped field's knobs, unchanged in name, default and meaning
        ("AmplitudeM", b.scalar("WaveAmplitudeM", d["WaveAmplitudeM"])),
        ("BaseWavelengthM", b.scalar("WaveBaseWavelengthM", d["WaveBaseWavelengthM"])),
        ("DirBaseDeg", b.scalar("WaveDirBaseDeg", d["WaveDirBaseDeg"])),
        ("DirIncrementDeg", b.scalar("WaveDirIncrementDeg", d["WaveDirIncrementDeg"])),
        ("QuantPerVoxel", b.scalar("WaveQuantPerVoxel", d["WaveQuantPerVoxel"])),
        ("PatchContrast", b.scalar("WavePatchContrast", d["WavePatchContrast"])),
        # --- wind
        ("WindVecMS", wind),
        # 0 reproduces the shipped whole-circle placement exactly; 1 is the wind
        # cone. It is a lerp and not a switch so it is also the A/B knob: an
        # owner can slide it on a material instance and watch the lake go from a
        # confused sea to a wind sea without a regeneration.
        ("WindDirAuthority", b.scalar("WindDirectionAuthority", d["WindDirectionAuthority"])),
        # Half-width of the directional cone at the PEAK octave, before the
        # 0.5 -> 1.5 tail ramp. 35 puts the peak octave within 7 degrees of the
        # wind and the shortest octave 46 degrees off it.
        ("WindSpreadDeg", b.scalar("WindSpreadDeg", d["WindSpreadDeg"])),
        # The calibration speed: at this wind the field is EXACTLY the shipped
        # one. Everything else about the wind response is a ratio to it.
        ("WindRefSpeedMS", b.scalar("WindRefSpeedMS", d["WindRefSpeedMS"])),
        # Fetch-limited exponents, JONSWAP. Height ~ U^1, wavelength ~ U^0.68.
        # These are the physics; the module docstring shows the derivation and
        # why Pierson-Moskowitz (U^2 for both) is the wrong family for a lake.
        ("WindAmpExponent", b.scalar("WindAmpExponent", d["WindAmpExponent"])),
        ("WindLenExponent", b.scalar("WindLenExponent", d["WindLenExponent"])),
        ("WindPatchDrift", b.scalar("WindPatchDriftFrac", d["WindPatchDriftFrac"])),
        # --- the shore band
        ("DepthM", bathy["depth_m"]),
        ("Validity", bathy["validity"]),
        # REPLACES BathyWaveDampDepthM, AND THE DEFAULT MOVES 0.6 -> 0.15. That is
        # the one deliberate change of shipped behaviour in this module and it is
        # not a tuning tweak, so it gets the space:
        #
        # The old term damped the wave to zero over the first 0.6 m of depth. The
        # break depth for the shipped wave is 7.7 cm. So a wave arrived at the
        # depth where it should break with 16 percent of its height left -- it
        # faded out well offshore and almost nothing reached the beach. Measured
        # on a 2-D shore at four phases, peak crest inside the foamed region at
        # 5 m/s: 1.22 cm with the 0.6 m floor, 4.88 cm with this one.
        #
        # Now the damping band IS the breaker band, floored only so that a
        # near-flat lake still fades over 1.5 voxels of depth rather than stopping
        # dead at the shoreline. Two consequences worth stating:
        #
        #   * WAVES NOW REACH THE SHORE. That is the feature, and it is a visible
        #     change from what ships. The regression recipe restores 0.6 m.
        #   * THE BANK-CLIPPING GUARANTEE IS NOW DERIVED RATHER THAN TUNED, which
        #     retires the reason WaveWpoFraction was pinned at 0.25
        #     (create_water_voxel_material.py:2385-2398, "no shore-damping term to
        #     stop a rising crest clipping through its own bank"). Inside the surf
        #     zone the linear ramp on a wave-proportional band gives
        #     H(d) = d / BreakDepthRatio = 0.78 d, i.e. the wave is DEPTH-LIMITED
        #     exactly as a real surf zone is, at any wind speed. The crest sits at
        #     ~0.4 of the local depth above the still surface and the geometry
        #     moves a quarter of that. It cannot clip a bank because it is bounded
        #     by the water it is standing in.
        ("SurfFloorM", b.scalar("BreakSurfFloorM", d["BreakSurfFloorM"])),
        # The breaker index, inverted: a wave breaks where depth < ratio * H.
        # 1.28 is 1/0.78, McCowan's solitary-wave limit.
        ("BreakDepthRatio", b.scalar("BreakDepthRatio", d["BreakDepthRatio"])),
        ("ShoalGain", b.scalar("BreakShoalGain", d["BreakShoalGain"])),
        ("CrestThreshold", b.scalar("BreakCrestThreshold", d["BreakCrestThreshold"])),
        ("MinWaveHeightM", b.scalar("BreakMinWaveHeightM", d["BreakMinWaveHeightM"])),
        ("PeakGain", b.scalar("BreakPeakGain", d["BreakPeakGain"])),
        # The A/B on the whole breaking effect, as a runtime scalar rather than a
        # generation-time arm. This one is safe as a parameter where the
        # shoreline-foam arm was not: VOXEL_SHORE_FX exists because zeroing a
        # gain measures nothing about GPU cost
        # (create_water_voxel_material.py:550-560), and this gain is not being
        # used to measure cost -- it is here so the owner can turn surf off in a
        # screenshot without a regeneration.
        ("FoamGain", b.scalar("BreakFoamGain", d["BreakFoamGain"])),
    ]
    for pin, src in wiring:
        b.link(src, "", node, pin)

    return {
        "node": node,
        "gradient": b.mask(node, "", r=True, g=True),
        "height_m": b.mask(node, "", b=True),
        "breaking": b.mask(node, "", a=True),
        "wind": wind,
        "wind_source": wind_source,
    }


def summary_lines(wind_source=None):
    """The wind model as text, for the generator's log.

    water_optics.py does this and the reason transfers exactly: "were these two
    built from the same numbers" should be answerable from two logs rather than
    by opening two assets. Here the two are the water material and whatever the
    weather subsystem ends up publishing, and the line that matters is the
    interface one.
    """
    lines = [
        "wind waves: fetch-limited (JONSWAP) scaling about a %.1f m/s reference"
        % DEFAULTS["WindRefSpeedMS"],
        "  amplitude ~ U^%.2f, wavelength ~ U^%.2f, phase speed ~ sqrt(wavelength)"
        % (DEFAULTS["WindAmpExponent"], DEFAULTS["WindLenExponent"]),
        "  directional cone %.0f deg half-width at the peak octave, 0.5x..1.5x over %d octaves"
        % (DEFAULTS["WindSpreadDeg"], OCTAVES),
        "  breaking at depth < %.2f x significant wave height; the shore damping uses"
        % DEFAULTS["BreakDepthRatio"],
        "  the same band, floored at %.2f m, so the wave is depth-limited in the surf zone"
        % DEFAULTS["BreakSurfFloorM"],
        "  interface: MPC_VoxelSky.%s (velocity m/s, world XY, points DOWNWIND)"
        % WIND_VECTOR_PARAM,
        "  interface: MPC_VoxelSky.%s (1 once the weather field has published)"
        % WIND_VALID_PARAM,
    ]
    if wind_source is not None:
        lines.append("  wind source THIS BUILD: %s" % wind_source)
    return lines
