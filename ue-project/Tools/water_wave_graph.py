def octave_spread_shape(n=OCTAVES):
    """The per-octave direction offset, in units of WindSpreadDeg.

    ONE DEFINITION, injected into the HLSL by `wave_code()`, so the shader and
    any offline transcription of it read the same table. Two properties, both
    argued at length in the module docstring:

      * frac((i + 0.5) * phi) is a golden-ratio low-discrepancy sequence, mapped
        to [-1, +1]. It spreads the eight directions evenly through the cone
        with no two equal and no repeat -- and the +0.5 offset is there so that
        no octave lands on exactly 0, i.e. exactly on the wind axis.
      * the 0.5 -> 1.5 width ramp reproduces the observed narrowing of
        directional spread at the spectral peak (Mitsuyasu's cos^2s model, s
        largest at the peak): the long heavy octaves line up with the wind and
        the short ones fan out.
    """
    phi = 0.6180339887498949
    out = []
    for i in range(n):
        low_disc = ((i + 0.5) * phi) % 1.0          # [0, 1)
        signed = 2.0 * low_disc - 1.0               # [-1, +1], never 0
        width = 0.5 + float(i) / float(n - 1)       # 0.5 at the peak -> 1.5 in the tail
        out.append(signed * width)
    return out


def wave_code():
    """The HLSL body of the WaveField Custom node.

    Built as a string rather than typed as one so the per-octave spread table
    comes from `octave_spread_shape()` and cannot drift from it. There is no
    other formatting in here -- everything else is literal HLSL, and it is
    deliberately readable as the mathematics it is (the argument for a Custom
    node over ~130 hand-wired expression nodes is at
    create_water_voxel_material.py:680-691).
    """
    spread_table = ", ".join("%.6ff" % v for v in octave_spread_shape())
    code = _WAVE_CODE_TEMPLATE % {
        "spread": spread_table,
        "octaves": OCTAVES,
        "field_crest": FIELD_CREST,
        "hs_gain": HS_PER_RMS * FIELD_RMS,
        "shoal_start": SHOAL_START_RATIO,
    }

    # EVERY DECLARED PIN MUST BE READ BY THE HLSL, checked here rather than
    # discovered in the editor. A Custom node input that the code never
    # references is not an error to the compiler -- the pin is simply ignored --
    # so renaming a parameter and missing one end produces a material that
    # builds, runs, and quietly uses a value nobody is feeding it any more. This
    # is the same class of silence as an unresolved CollectionParameter
    # compiling to a constant (sky_star_graph.py:196-207), and it gets the same
    # treatment: raise at authoring time.
    #
    # Word-boundary matching, not substring: "DepthM" is a substring of
    # "BreakDepthRatio" and "SurfFloorM" is not a substring of anything, so a
    # naive `in` test would pass a pin that only appears inside another name.
    missing = [nm for nm in WAVE_INPUTS
               if not re.search(r"\b%s\b" % re.escape(nm), code)]
    if missing:
        raise RuntimeError(
            "WaveField declares input pins the HLSL never reads: %s. Either the "
            "pin is dead and should come out of WAVE_INPUTS, or a rename missed "
            "one end -- in which case the material would have compiled anyway "
            "and silently stopped tracking that parameter." % missing)
    return code


# The HLSL. Read the module docstring first -- every non-obvious line here has
# its argument there rather than a duplicate of it beside the code.
#
# NO literal '%' may appear below: this string is %-formatted.
_WAVE_CODE_TEMPLATE = """
// ONE evaluation, FOUR outputs: float4(dH/dx, dH/dy, H, breaking).
//   .xy  surface gradient, dimensionless (metres of rise per metre of run)
//   .z   height, metres, zero-mean
//   .w   breaking signal, 0..1, for foam
// The gradient drives MP_NORMAL and the height drives MP_WORLD_POSITION_OFFSET,
// so they are two halves of one field and cannot disagree about a crest.
float2 p = PosM;

// Voxel-grid quantisation: the stylisation knob, and the anti-aliasing.
if (QuantPerVoxel > 0.0)
{
    float k = QuantPerVoxel * 10.0;   // samples per metre; 10 = one per 10 cm voxel
    p = floor(p * k) / k;
}

const float DRAG_MULT = 0.2;
// Mean of exp(sin(x)-1)*0.5 over a full period = 0.5 * I0(1) * e^-1.
const float MEAN_WAVE = 0.2329;
// Absolute crest of the normalised field, 0.5 - MEAN_WAVE. Used ONLY to put H
// on a [-1,1]-ish scale for the crest test and the peaking.
const float FIELD_CREST = %(field_crest).4f;
// 4 * (rms of the normalised field) -- significant wave height per unit of
// AmplitudeM, in metres. This and not the crest is what the breaker criterion
// wants; see water_wave_graph's FIELD_RMS for the 2.2x error that using the
// crest instead produces.
const float HS_GAIN = %(hs_gain).5f;
const float SHOAL_START = %(shoal_start).1f;
// Per-octave direction offset in units of WindSpreadDeg. Generated by
// water_wave_graph.octave_spread_shape() -- one definition, injected here.
const float SPREAD_SHAPE[%(octaves)d] = { %(spread)s };

// --- WIND: SPEED AND DIRECTION FROM ONE VECTOR --------------------------
// A velocity in m/s along world +X and +Y. One value, so speed and direction
// cannot be inconsistent, and calm is exactly zero rather than a special case.
// The max() is the only NaN guard needed: at zero wind windDir is (0,0), and
// every term it feeds is multiplied by a speed that is also zero.
float  windSpeed = length(WindVecMS);
float2 windDir   = WindVecMS / max(windSpeed, 1.0e-4);
float  u         = windSpeed / max(WindRefSpeedMS, 0.1);

// Fetch-limited growth: height ~ U^1, wavelength ~ U^0.68 (JONSWAP, see the
// module docstring for why NOT Pierson-Moskowitz). Both are exactly 1.0 at the
// reference speed, which is what makes the shipped field reproducible.
//
// The amplitude term reads u directly, so wind 0 gives amplitude EXACTLY 0 --
// dead calm, with the breaking term gated to zero by the same value. The
// wavelength term reads max(u, 0.2) instead, because a wavelength that
// collapses toward zero would send the octave frequencies to infinity long
// before the amplitude reached zero, and a field of infinite frequency at zero
// amplitude is a field of NaNs waiting for a rounding error.
float  ampScale = pow(max(u, 0.0), max(WindAmpExponent, 0.01));
float  lenScale = pow(max(u, 0.2), max(WindLenExponent, 0.0));
float  lambda0  = max(BaseWavelengthM * lenScale, 0.15);

// Deep-water dispersion, omega = sqrt(g k): a longer wave oscillates slower but
// its crests travel faster. 2.0 is the shipped base time multiplier, and the
// sqrt is exactly 1.0 at the reference speed.
float  omega0 = 2.0 * sqrt(BaseWavelengthM / max(lambda0, 1.0e-4));

// --- WIND: STEERING -----------------------------------------------------
// atan2(-w.x, -w.y) and not atan2(w.x, w.y). `ang` names the wavefront's UPWIND
// normal, because the loop below writes `+ T * tmul`, which makes crests travel
// along -d. Negating here puts travel on +windDir, i.e. downwind. This is the
// classic 180-degree bug and it is the reason the sign is spelled out.
float  upwindAng = atan2(-windDir.x, -windDir.y);
float  baseAng   = radians(DirBaseDeg);
// Unwrap before blending, so a wind turning through the 359->1 degree boundary
// does not swing the field the long way round at intermediate authorities.
float  dA = upwindAng - baseAng;
dA -= 6.2831853 * round(dA * 0.15915494);
baseAng += WindDirAuthority * dA;

float  spreadRad = radians(WindSpreadDeg);
float  dIncRad   = radians(DirIncrementDeg);

float2 pos    = p;
float  freq   = 6.2831853 / lambda0;
float  tmul   = omega0;
float  weight = 1.0;
float  sumH   = 0.0;
float  sumW   = 0.0;
float2 sumD   = float2(0.0, 0.0);

[unroll]
for (int i = 0; i < %(octaves)d; ++i)
{
    // Authority 0: the shipped whole-circle golden-angle placement, exactly.
    // Authority 1: a directional cone about the wind, narrow at the peak octave
    // and broad in the tail.
    float  ang = baseAng + lerp(dIncRad * i, spreadRad * SPREAD_SHAPE[i], WindDirAuthority);
    float2 d = float2(sin(ang), cos(ang));
    float  x = dot(d, pos) * freq + T * tmul;
    float  wv  = exp(sin(x) - 1.0) * 0.5;
    float  dwv = wv * cos(x);

    // Drag: this octave warps the sample position seen by the next one.
    pos += d * (-dwv) * weight * DRAG_MULT;

    sumH += wv * weight;
    sumD += d * (dwv * freq * weight);
    sumW += weight;

    weight *= 0.8;      // lerp(weight, 0, 0.2)
    freq   *= 1.42;     // non-commensurate on purpose
    tmul   *= 1.07;     // NOT the dispersion-correct 1.19; see the docstring
}

float  invW = 1.0 / max(sumW, 1e-6);
float  H = (sumH * invW) - MEAN_WAVE;
float2 G = sumD * invW;

// --- CALM AND CHOPPY PATCHES, NOW BLOWN DOWNWIND ------------------------
// The two diagonal sines at ~180 m and ~232 m are the shipped field's, verbatim.
// What is new is that the sample position is advected by the wind, so gust cells
// drift instead of merely breathing in place. Gated by WindDirAuthority so the
// regression recipe reproduces the shipped patch field exactly.
float2 pp = p - windDir * (windSpeed * T * WindPatchDrift * WindDirAuthority);
float lfa = sin(dot(pp, float2( 0.0349,  0.0217)) + T * 0.031);
float lfb = sin(dot(pp, float2(-0.0161,  0.0271)) + T * 0.0193);
float patch = saturate(0.5 + 0.35 * lfa + 0.35 * lfb);
float amp = AmplitudeM * ampScale * lerp(1.0 - PatchContrast, 1.0 + PatchContrast, patch);

// --- TWO NESTED DEPTH BANDS ---------------------------------------------
// Hs is the OFFSHORE significant wave height: what the wave would be if the bed
// were not in the way. That is the height the breaker criterion wants -- where
// a wave breaks is set by the wave that arrives, not by the one that is left
// after damping.
float Hs = amp * HS_GAIN;

// THE INNER BAND, WHERE THE WAVE BREAKS. depth < BreakDepthRatio * Hs, i.e.
// McCowan's H/d = 0.78 inverted. It is proportional to the wave, so it shrinks
// to nothing at zero wind and widens in a storm, with no separate knob.
float dBreak = max(BreakDepthRatio * Hs, 1.0e-3);

// THE OUTER BAND, WHERE THE WAVE DIES. Normally EQUAL to the break depth -- a
// wave breaks and then dissipates across the surf zone to the waterline, so the
// two bands coincide and the damping is the exact complement of the breaking.
// SurfFloorM is only a floor for tiny waves, so that even a millimetre of ripple
// still fades over a couple of voxels of depth instead of stopping dead at the
// shoreline.
float dSurf = max(dBreak, SurfFloorM);

float xb = DepthM / dBreak;              // 1 at the break line
float xr = DepthM / max(dSurf, 0.02);    // 1 at the outer edge of the damping

// WHERE THERE IS NO FIELD, THERE IS NO DAMPING AND NO BREAKING. Same lerp, same
// reason as the term this replaces: a run with no fine tier must look exactly
// as it does today rather than with its waves silently switched off.
float surf  = lerp(1.0, saturate(xr), Validity);
float shoal = 1.0 + ShoalGain * saturate((SHOAL_START - xb) * (1.0 / (SHOAL_START - 1.0))) * Validity;
float ampEff = amp * surf * shoal;

// --- BREAKING -----------------------------------------------------------
// The complement of the INNER band. Three gates, all of them load-bearing
// against a permanent white ring round a still lake:
//   band   -- only shoreward of the break line, which is proportional to the
//             wave. No wave, no band, whatever the damping depth is set to.
//   crest  -- foam rides the crests, so it travels with them; the threshold
//             relaxes to nothing at the waterline, where swash really is solid.
//   size   -- a second, absolute floor under the first, so a barely-rippled
//             lake cannot foam even where its bed comes up to a centimetre.
//   valid  -- no baked depth, no breaking.
float band     = 1.0 - lerp(1.0, saturate(xb), Validity);
float hNorm    = H * (1.0 / FIELD_CREST);
float crest    = saturate((hNorm - CrestThreshold) / max(1.0 - CrestThreshold, 1.0e-3));
float sizeGate = saturate(Hs / max(MinWaveHeightM, 1.0e-3));
float breaking = saturate(band * lerp(crest, 1.0, band) * sizeGate * Validity * FoamGain);

// --- THE PEAKED SHAPE ---------------------------------------------------
// f(H) = H + k*max(H,0)^2 / peak lifts crests and leaves troughs alone, which
// is what a shoaling wave does. The gradient is scaled by the ANALYTIC
// derivative f'(H) = 1 + 2k*max(H,0)/peak in the same breath, so the normal and
// the displacement stay one field. The dk/dp term is omitted; see the docstring.
float kPeak = PeakGain * breaking;
float hPos  = max(H, 0.0);
float hNormPos = hPos * (1.0 / FIELD_CREST);
H += kPeak * hNormPos * hPos;
G *= (1.0 + 2.0 * kPeak * hNormPos);

return float4(G * ampEff, H * ampEff, breaking);
"""


