#!/usr/bin/env node
// Embeds the six menu backdrops into the bundle as data URIs.
//
// WHY EMBEDDED AND NOT LINKED. A design built with this system receives only
// the JS bundle plus the transitive @import closure of styles.css -- there is
// no static file server behind it, so a `<img src="battle.jpg">` would 404 in
// every design the agent produces. Data URIs are the only delivery route that
// survives that, so they ride in the JS bundle (one copy) rather than the CSS
// (which would duplicate them into every rendered design's stylesheet).
//
// Sources are re-encoded to 1024px by tools/prepare-backgrounds.py; the 1920px
// originals stay in assets/backgrounds/ as the reference. These sit behind a
// 55-62% wash in every screen that uses them, which is why a web-weight encode
// costs nothing visible.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, dirname, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = resolve(here, '../assets/backgrounds/web');
const files = readdirSync(dir).filter((f) => f.endsWith('.jpg')).sort();
if (files.length === 0) {
  console.error('[BG] no encoded backgrounds in assets/backgrounds/web - run tools/prepare-backgrounds.py first');
  process.exit(1);
}

const camel = (s) => s.replace(/[_-](\w)/g, (_, c) => c.toUpperCase());
const out = [];
out.push('// GENERATED by tools/gen-backgrounds.mjs. Do not edit by hand.');
out.push('//');
out.push('// The six menu backdrops, ported from the game with the rest of the front end.');
out.push('// Provenance and rights: assets/backgrounds/MENU_ART_CREDITS.md.');
out.push('');
let total = 0;
for (const f of files) {
  const buf = readFileSync(resolve(dir, f));
  total += buf.length;
  const name = camel(basename(f, extname(f)));
  // ANNOTATED `: string` DELIBERATELY. Without it TypeScript infers the literal
  // type and copies the entire base64 payload into the emitted .d.ts -- an
  // 845 KB declaration file that every downstream type-checker then has to
  // parse. The annotation widens it to `string` and the .d.ts stays a few KB.
  out.push(`const ${name}: string = 'data:image/jpeg;base64,${buf.toString('base64')}';`);
}
const names = files.map((f) => camel(basename(f, extname(f))));
out.push('');
out.push('/** The menu backdrops, by name. Every screen that takes a `background` accepts one of these keys. */');
out.push('export const backgrounds = {');
for (const n of names) out.push(`  ${n},`);
out.push('} as const;');
out.push('');
out.push('/** The names, in the order the game rotates them. */');
out.push(`export const backgroundNames = [${names.map((n) => `'${n}'`).join(', ')}] as const;`);
out.push('');
out.push('export type BackgroundName = (typeof backgroundNames)[number];');
writeFileSync(resolve(here, '../src/backgrounds.ts'), out.join('\n') + '\n');
console.log(`[BG] ${files.length} backdrops, ${(total / 1024).toFixed(1)} KB raw -> src/backgrounds.ts`);
