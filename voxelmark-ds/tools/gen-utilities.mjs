#!/usr/bin/env node
// Generates the utility class layer FROM the token file, so the two can never
// disagree.
//
// WHY THIS EXISTS AT ALL. The consumer of this design system is an agent that
// writes its own layout markup around these components, and it can only use a
// class vocabulary that actually resolves. A utility layer that is hand-written
// drifts from the palette the moment a colour is added, and the failure is
// silent -- the agent writes `vm-bg-parchment2`, nothing matches, and the
// design ships with a transparent background. Deriving every class from the
// emitted tokens makes "documented" and "exists" the same fact.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokensPath = resolve(here, '../src/styles/tokens.css');
const css = readFileSync(tokensPath, 'utf8');

// Colour tokens are the ones whose value is a hex or an rgba(); layout tokens
// carry px/s or are bare numbers. Only colours get colour utilities.
const colourNames = [];
for (const m of css.matchAll(/^\s*--vm-([a-z0-9-]+):\s*(#[0-9a-f]{3,8}|rgba?\([^)]*\))\s*;/gim)) {
  colourNames.push(m[1]);
}
if (colourNames.length === 0) {
  console.error('[UTIL] no colour tokens found in tokens.css - refusing to emit');
  process.exit(1);
}

const out = [];
out.push('/* GENERATED by tools/gen-utilities.mjs from src/styles/tokens.css.');
out.push(' * Do not edit by hand -- add the token and re-run `npm run tokens`.');
out.push(' *');
out.push(' * Every class below is derived from a token that exists, which is the point:');
out.push(' * these are the names that are safe to write in layout markup around the');
out.push(' * components.');
out.push(' */');
out.push('');

out.push('/* --- colour --- */');
for (const n of colourNames) {
  out.push(`.vm-bg-${n} { background-color: var(--vm-${n}); }`);
}
out.push('');
for (const n of colourNames) {
  out.push(`.vm-text-${n} { color: var(--vm-${n}); }`);
}
out.push('');
for (const n of colourNames) {
  out.push(`.vm-border-${n} { border-color: var(--vm-${n}); }`);
}
out.push('');

// The spacing scale is the set of gaps the front end actually uses, named by
// what they are rather than by an invented t-shirt scale.
const spacing = {
  'row': 'var(--vm-save-row-separation)',        /* 6px  */
  'sub': 'var(--vm-sub-panel-separation)',       /* 10px */
  'column': 'var(--vm-main-column-separation)',  /* 14px */
  'panel': 'var(--vm-sub-panel-padding)',        /* 16px */
  'loading': 'var(--vm-loading-separation)',     /* 18px */
  'title': 'var(--vm-title-to-buttons-spacer)',  /* 36px */
  'quit': 'var(--vm-quit-spacer)',               /* 80px */
};
out.push('/* --- spacing (the gaps the front end actually uses) --- */');
for (const [name, value] of Object.entries(spacing)) {
  out.push(`.vm-gap-${name} { gap: ${value}; }`);
  out.push(`.vm-p-${name} { padding: ${value}; }`);
}
out.push('');

const fontSizes = {
  'title': 'var(--vm-title-font-size)',        /* 84px */
  'loading': 'var(--vm-loading-title-size)',   /* 44px */
  'panel-title': 'var(--vm-sub-panel-title-size)', /* 32px */
  'button': 'var(--vm-button-font-size)',      /* 24px */
  'quip': 'var(--vm-loading-quip-size)',       /* 20px */
  'body': 'var(--vm-sub-panel-body-size)',     /* 18px */
  'row': 'var(--vm-save-row-font-size)',       /* 16px */
  'tip': 'var(--vm-loading-tip-size)',         /* 14px */
  'stamp': 'var(--vm-version-font-size)',      /* 12px */
};
out.push('/* --- type scale --- */');
for (const [name, value] of Object.entries(fontSizes)) {
  out.push(`.vm-type-${name} { font-size: ${value}; }`);
}
out.push('');

out.push('/* --- structure --- */');
out.push('.vm-border-hard { border: 2px solid #000; }');
out.push('.vm-border-thin { border: 1px solid #000; }');
out.push('.vm-stack { display: flex; flex-direction: column; }');
out.push('.vm-row { display: flex; flex-direction: row; align-items: center; }');
out.push('.vm-center { display: flex; align-items: center; justify-content: center; }');
out.push('.vm-fill { position: absolute; inset: 0; }');

writeFileSync(resolve(here, '../src/styles/utilities.css'), out.join('\n') + '\n');
console.log(
  `[UTIL] ${colourNames.length} colours x3 + ${Object.keys(spacing).length} spacings x2 + ` +
    `${Object.keys(fontSizes).length} sizes -> src/styles/utilities.css`,
);
